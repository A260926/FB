// Windowless CPU contract test for the sphere UV parameterization.
//
// This file is an explicit Cargo test target (see `[[test]]` in devcheck/Cargo.toml), not a
// binary. It reuses the module layout from `core_modules.rs` so the production sources are
// compiled exactly as the devcheck witnesses compile them.
include!("core_modules.rs");

use collision::{
    BVHNode, Hitable, HitableList, Instance, MovingSphere, Ray, RayHit, Sphere, SpheresSoA,
    sphere_uv,
};
use glam::{Affine3A, Quat, Vec3, vec3};
use rand::RngExt;
use rand::SeedableRng;
use rand_xoshiro::Xoshiro256Plus;
use scene::{Scene, World};
use std::path::Path;
use std::ptr;

const UV_TOLERANCE: f64 = 2.0e-6;

// Four distinct columns, and each column differs between the two rows. The texture is
// generated by the test itself and loaded through the normal `RgbImage` path.
const TOP_ROW: [[u8; 3]; 4] = [
    [255, 0, 0],   // red
    [0, 255, 0],   // green
    [0, 0, 255],   // blue
    [255, 255, 0], // yellow
];
const BOTTOM_ROW: [[u8; 3]; 4] = [
    [255, 0, 255], // magenta
    [0, 255, 255], // cyan
    [255, 255, 255], // white
    [255, 128, 0], // orange
];

fn png_path(dir: &Path, name: &str) -> String {
    dir.join(name).to_str().unwrap().to_owned()
}

fn make_texture_file(dir: &Path) -> texture::RgbImage {
    let mut pixels = [0u8; 4 * 2 * 3];
    for col in 0..4 {
        for channel in 0..3 {
            pixels[col * 3 + channel] = TOP_ROW[col][channel];
            pixels[12 + col * 3 + channel] = BOTTOM_ROW[col][channel];
        }
    }
    let path = png_path(dir, "sphere_uv_source.png");
    image::save_buffer(&path, &pixels, 4, 2, image::ColorType::Rgb8).unwrap();

    for col in 1..4 {
        assert_ne!(TOP_ROW[col], TOP_ROW[col - 1], "generated columns must differ");
        assert_ne!(
            BOTTOM_ROW[col],
            BOTTOM_ROW[col - 1],
            "generated columns must differ"
        );
    }
    for col in 0..4 {
        assert_ne!(
            TOP_ROW[col], BOTTOM_ROW[col],
            "generated rows must differ in column {}",
            col
        );
    }

    texture::RgbImage::open(&path)
}

/// Independent reference implementation of the documented lat/long convention, evaluated
/// in f64. Deliberately does not call the production `sphere_uv` helper.
fn reference_uv(n: Vec3) -> (f64, f64) {
    let x = n.x as f64;
    let y = n.y as f64;
    let z = n.z as f64;
    let len = (x * x + y * y + z * z).sqrt();
    let (x, y, z) = if len > 0.0 {
        (x / len, y / len, z / len)
    } else {
        (0.0, 0.0, 0.0)
    };
    let phi = z.atan2(x);
    let mut u = 1.0 - (phi + std::f64::consts::PI) / (2.0 * std::f64::consts::PI);
    u -= u.floor();
    if u >= 1.0 {
        u = 0.0;
    }
    let v = 0.5 + y.clamp(-1.0, 1.0).asin() / std::f64::consts::PI;
    (u, v)
}

/// Mirror of `RgbImage::value`'s discrete texel selection for this test's 4x2 image.
fn expected_color(u: f64, v: f64) -> Vec3 {
    let i = ((u * 4.0) as i32).clamp(0, 3) as usize;
    let j = (((1.0 - v) * 2.0 - 0.001) as i32).clamp(0, 1) as usize;
    let [r, g, b] = if j == 0 {
        TOP_ROW[i]
    } else {
        BOTTOM_ROW[i]
    };
    vec3(r as f32 / 255.0, g as f32 / 255.0, b as f32 / 255.0)
}

fn assert_uv(path: &str, n: Vec3, expected: (f64, f64), actual: (f32, f32)) {
    let du = (actual.0 as f64 - expected.0).abs();
    let dv = (actual.1 as f64 - expected.1).abs();
    if !actual.0.is_finite() || !actual.1.is_finite() || du > UV_TOLERANCE || dv > UV_TOLERANCE {
        panic!(
            "sphere_uv_contract failure path={} local_direction=({:.9}, {:.9}, {:.9}) \
             expected_uv=({:.12}, {:.12}) actual_uv=({:.12}, {:.12}) du={:.3e} dv={:.3e}",
            path, n.x, n.y, n.z, expected.0, expected.1, actual.0, actual.1, du, dv
        );
    }
}

fn assert_vec_close(path: &str, n: Vec3, what: &str, expected: Vec3, actual: Vec3) {
    let delta = (actual - expected).length();
    if !delta.is_finite() || delta > 2.0e-5 {
        panic!(
            "sphere_uv_contract failure path={} local_direction=({:.9}, {:.9}, {:.9}) \
             {} expected={:?} actual={:?} delta={:.3e}",
            path, n.x, n.y, n.z, what, expected, actual, delta
        );
    }
}

fn assert_scalar_close(path: &str, n: Vec3, what: &str, expected: f32, actual: f32) {
    if !actual.is_finite() || (actual - expected).abs() > 2.0e-5 {
        panic!(
            "sphere_uv_contract failure path={} local_direction=({:.9}, {:.9}, {:.9}) \
             {} expected={:.9} actual={:.9}",
            path, n.x, n.y, n.z, what, expected, actual
        );
    }
}

fn assert_color(path: &str, n: Vec3, expected: Vec3, actual: Vec3) {
    let delta = (actual - expected).length();
    if !delta.is_finite() || delta > 3.0e-6 {
        panic!(
            "sphere_uv_contract failure path={} local_direction=({:.9}, {:.9}, {:.9}) \
             texel expected={:?} actual={:?} delta={:.3e}",
            path, n.x, n.y, n.z, expected, actual, delta
        );
    }
}

fn ray_for_local_direction(n: Vec3, time: f32) -> Ray {
    Ray::new(n * 3.0, -n, time)
}

fn check_hit_geometry(path: &str, n: Vec3, centre: Vec3, radius: f32, hit: &RayHit) {
    assert_scalar_close(path, n, "hit.t", 2.0 * radius, hit.t);
    assert_vec_close(path, n, "hit.point", centre + n * radius, hit.point);
    assert_vec_close(path, n, "hit.normal", n, hit.normal);
}

/// Confirm `run` consumed no random numbers. The control RNG is advanced by the same
/// number of *test* draws after the operation, so both streams must agree.
fn assert_no_rng_consumed(path: &str, run: impl FnOnce(&mut Xoshiro256Plus)) {
    let mut used = Xoshiro256Plus::seed_from_u64(0x5eed_1234_5678_9abc);
    let mut control = Xoshiro256Plus::seed_from_u64(0x5eed_1234_5678_9abc);
    run(&mut used);
    let a = used.random::<u64>();
    let b = control.random::<u64>();
    assert_eq!(
        a, b,
        "sphere_uv_contract failure path={} ray_hit consumed extra random numbers",
        path
    );
}

fn camera_along(n: Vec3, aspect: f32) -> camera::Camera {
    camera::Camera::new(
        n * 4.0,
        Vec3::ZERO,
        Vec3::Y,
        10.0,
        aspect,
        0.0,
        1.0,
        0.0,
        0.0,
    )
}

fn save_render(path: &str, buffer: &[(f32, f32, f32)], width: u32, height: u32) {
    let mut bytes = Vec::with_capacity(buffer.len() * 3);
    for row in buffer.chunks(width as usize).rev() {
        for rgb in row {
            let srgb = math::linear_to_srgb(*rgb);
            bytes.push(srgb.0);
            bytes.push(srgb.1);
            bytes.push(srgb.2);
        }
    }
    image::save_buffer(path, &bytes, width, height, image::ColorType::Rgb8).unwrap();
}

/// Render the same visible sphere twice: once with a direct emissive image and once with a
/// two-level `Checker` whose leaves are that same image. Returns the direct buffer, the
/// nested buffer and the camera so the caller can reproduce each primary ray.
fn render_direct_and_nested(
    img: &texture::RgbImage,
    view_direction: Vec3,
    params: &params::Params,
    out_dir: &Path,
    label: &str,
) -> (
    Vec<(f32, f32, f32)>,
    Vec<(f32, f32, f32)>,
    camera::Camera,
) {
    let tex = texture::rgb_image(img);
    let sphere = Sphere::new(Vec3::ZERO, 2.0);

    let direct_material = material::diffuse_light(&tex);
    let direct_hitable = Hitable::Sphere(&sphere, &direct_material);
    let direct_scene = Scene::new(World::Hitable(direct_hitable), Some(Vec3::ZERO));

    // Two nesting levels, both branches of every Checker refer to the same image.
    let inner = texture::checker(&tex, &tex);
    let outer = texture::checker(&inner, &inner);
    let nested_material = material::diffuse_light(&outer);
    let nested_hitable = Hitable::Sphere(&sphere, &nested_material);
    let nested_scene = Scene::new(World::Hitable(nested_hitable), Some(Vec3::ZERO));

    let cam = camera_along(
        view_direction,
        params.width as f32 / params.height as f32,
    );
    let mut direct = vec![(0.0, 0.0, 0.0); (params.width * params.height) as usize];
    let mut nested = vec![(0.0, 0.0, 0.0); (params.width * params.height) as usize];

    let direct_rays = direct_scene.update(params, &cam, 0, &mut direct);
    let nested_rays = nested_scene.update(params, &cam, 0, &mut nested);
    assert_eq!(
        direct_rays,
        (params.width * params.height * params.samples) as usize,
        "direct render ray count"
    );
    assert_eq!(
        nested_rays, direct_rays,
        "nested render ray count must match direct render"
    );

    save_render(
        &png_path(out_dir, &format!("{}_direct.png", label)),
        &direct,
        params.width,
        params.height,
    );
    save_render(
        &png_path(out_dir, &format!("{}_nested.png", label)),
        &nested,
        params.width,
        params.height,
    );

    (direct, nested, cam)
}

fn texel_boundary_is_stable(u: f64, v: f64) -> bool {
    let fu = u * 4.0;
    let fv = (1.0 - v) * 2.0 - 0.001;
    let du = (fu - fu.round()).abs();
    let dv = (fv - fv.round()).abs();
    du > 2.0e-3 && dv > 2.0e-3
}

#[test]
fn sphere_uv_contract() {
    let out_dir = std::env::temp_dir().join(format!("pathtrace-sphere-uv-{}", std::process::id()));
    std::fs::create_dir_all(&out_dir).unwrap();

    let img = make_texture_file(&out_dir);
    let tex = texture::rgb_image(&img);

    // ---------------------------------------------------------------------------------
    // 1. Independent UV assertions through Sphere::ray_hit for axes, seam, poles and
    //    general oblique directions.
    // ---------------------------------------------------------------------------------
    let unit = Sphere::new(Vec3::ZERO, 1.0);
    let seam_eps = 1.0e-3f32;
    let seam_plus_n = vec3(-seam_eps.cos(), 0.0, seam_eps.sin());
    let seam_minus_n = vec3(-seam_eps.cos(), 0.0, -seam_eps.sin());
    let axis_cases: &[(&str, Vec3, (f64, f64))] = &[
        ("axis +X", vec3(1.0, 0.0, 0.0), (0.5, 0.5)),
        ("axis +Z", vec3(0.0, 0.0, 1.0), (0.25, 0.5)),
        ("axis -Z", vec3(0.0, 0.0, -1.0), (0.75, 0.5)),
        ("axis -X with +0 z", vec3(-1.0, 0.0, 0.0), (0.0, 0.5)),
        ("axis -X with -0 z", vec3(-1.0, 0.0, -0.0), (0.0, 0.5)),
        ("north pole", vec3(0.0, 1.0, 0.0), (0.5, 1.0)),
        ("south pole", vec3(0.0, -1.0, 0.0), (0.5, 0.0)),
        // The seam sides approach -X from each side; the exact -X point itself is 0 above.
        ("seam side +", seam_plus_n, reference_uv(seam_plus_n)),
        ("seam side -", seam_minus_n, reference_uv(seam_minus_n)),
    ];

    for &(label, n, expected) in axis_cases {
        let ray = ray_for_local_direction(n, 0.5);
        let hit = unit
            .ray_hit(&ray, scene::MIN_T, scene::MAX_T)
            .unwrap_or_else(|| panic!("sphere_uv_contract: expected a hit for {}", label));
        assert_uv(label, n, expected, (hit.u, hit.v));
        check_hit_geometry(label, n, Vec3::ZERO, 1.0, &hit);

        if texel_boundary_is_stable(expected.0, expected.1) {
            assert_color(
                label,
                n,
                expected_color(expected.0, expected.1),
                tex.value(hit.u, hit.v, hit.point),
            );
        }
    }

    // The two sides of the seam must bracket the -X seam, and the exact seam must be 0.
    let seam_plus = unit
        .ray_hit(
            &ray_for_local_direction(seam_plus_n, 0.5),
            scene::MIN_T,
            scene::MAX_T,
        )
        .unwrap();
    let seam_minus = unit
        .ray_hit(
            &ray_for_local_direction(seam_minus_n, 0.5),
            scene::MIN_T,
            scene::MAX_T,
        )
        .unwrap();
    assert!(seam_plus.u < 1.0e-3, "seam + side should be near u=0");
    assert!(seam_minus.u > 1.0 - 1.0e-3, "seam - side should be near u=1");
    let seam_zero = unit
        .ray_hit(&ray_for_local_direction(vec3(-1.0, 0.0, 0.0), 0.5), scene::MIN_T, scene::MAX_T)
        .unwrap();
    assert_eq!(seam_zero.u, 0.0, "exact -X seam longitude must be 0");

    // Near the poles the parameterization must stay finite (atan2(0, 0) is 0 and the
    // latitude is clamped), regardless of how small the horizontal components become.
    for n in [
        vec3(1.0e-6, 1.0, 0.0).normalize(),
        vec3(0.0, 1.0, -0.0),
        vec3(1.0e-9, -1.0, 1.0e-9).normalize(),
        vec3(0.0, -1.0, 0.0),
    ] {
        let ray = ray_for_local_direction(n, 0.5);
        let hit = unit.ray_hit(&ray, scene::MIN_T, scene::MAX_T).unwrap();
        let (u, v) = (hit.u, hit.v);
        assert!(
            u.is_finite() && v.is_finite(),
            "near-pole UV became non-finite: path=near_pole n={:?} uv=({}, {})",
            n,
            u,
            v
        );
        assert!((0.0..1.0).contains(&u), "u outside [0,1): {} for n={:?}", u, n);
        assert!((0.0..=1.0).contains(&v), "v outside [0,1]: {} for n={:?}", v, n);
        if n.x == 0.0 && n.z == 0.0 {
            assert_eq!(hit.u, 0.5, "u at an exact pole is fixed at 0.5");
        }
    }

    // General oblique directions, where the expected value comes from the independent
    // reference implementation.
    for n in [
        vec3(0.3, 0.4, -0.5).normalize(),
        vec3(-0.3, 0.4, 0.5).normalize(),
        vec3(0.5, -0.4, 0.3).normalize(),
    ] {
        let label = "general";
        let ray = ray_for_local_direction(n, 0.5);
        let hit = unit.ray_hit(&ray, scene::MIN_T, scene::MAX_T).unwrap();
        assert_uv(label, n, reference_uv(n), (hit.u, hit.v));
        check_hit_geometry(label, n, Vec3::ZERO, 1.0, &hit);
        let expected = reference_uv(n);
        if texel_boundary_is_stable(expected.0, expected.1) {
            assert_color(
                label,
                n,
                expected_color(expected.0, expected.1),
                tex.value(hit.u, hit.v, hit.point),
            );
        }
    }

    // The production helper is public for compatibility and must agree with the same
    // convention, including signed zero at the seam.
    for n in [Vec3::X, Vec3::Z, -Vec3::Z, -Vec3::X, vec3(-1.0, 0.0, -0.0), Vec3::Y, -Vec3::Y] {
        assert_uv("sphere_uv helper", n, reference_uv(n), sphere_uv(n));
    }

    // ---------------------------------------------------------------------------------
    // 2. MovingSphere at two times: the centre is evaluated at ray.time.
    // ---------------------------------------------------------------------------------
    let moving = MovingSphere::new(
        vec3(-0.5, 0.25, -0.75),
        vec3(0.75, -0.2, 0.5),
        0.0,
        1.0,
        1.5,
    );
    for time in [0.25f32, 0.75f32] {
        let centre = moving.centre(time);
        for n in [
            vec3(0.3, 0.4, -0.5).normalize(),
            vec3(-0.3, 0.4, 0.5).normalize(),
        ] {
            let radius = moving.radius();
            let ray = Ray::new(centre + n * (3.0 * radius), -n, time);
            let hit = moving
                .ray_hit(&ray, scene::MIN_T, scene::MAX_T)
                .unwrap_or_else(|| {
                    panic!(
                        "sphere_uv_contract: moving sphere missed at time {} n={:?}",
                        time, n
                    )
                });
            let label = format!("moving sphere time={}", time);
            assert_uv(&label, n, reference_uv(n), (hit.u, hit.v));
            check_hit_geometry(&label, n, centre, radius, &hit);
            let expected = reference_uv(n);
            if texel_boundary_is_stable(expected.0, expected.1) {
                assert_color(
                    &label,
                    n,
                    expected_color(expected.0, expected.1),
                    tex.value(hit.u, hit.v, hit.point),
                );
            }
        }
    }

    // ---------------------------------------------------------------------------------
    // 3. Hitable, HitableList, BVH and SpheresSoA (scalar and default dispatch) must all
    //    return the same geometric UV, t, point, normal and material.
    // ---------------------------------------------------------------------------------
    let centre = vec3(0.4, -0.3, 0.2);
    let radius = 0.7f32;
    let sphere = Sphere::new(centre, radius);
    let direct_material = material::diffuse_light(&tex);
    let hitable = Hitable::Sphere(&sphere, &direct_material);
    let n = vec3(0.3, 0.4, -0.5).normalize();
    let expected = reference_uv(n);
    let ray = Ray::new(centre + n * (3.0 * radius), -n, 0.5);

    let mut bvh_rng = Xoshiro256Plus::seed_from_u64(11);
    let arena = typed_arena::Arena::new();
    let mut bvh_hitables = vec![hitable];
    let bvh_root = BVHNode::new(&mut bvh_rng, &mut bvh_hitables, &arena).unwrap();
    let list = HitableList::new(vec![hitable]);
    let soa = SpheresSoA::new(&[hitable]);

    // Hitable
    let (h_hit, h_mat) = hitable
        .ray_hit(&ray, scene::MIN_T, scene::MAX_T, &mut Xoshiro256Plus::seed_from_u64(1))
        .unwrap();
    assert_uv("Hitable::Sphere", n, expected, (h_hit.u, h_hit.v));
    check_hit_geometry("Hitable::Sphere", n, centre, radius, &h_hit);
    assert!(ptr::eq(h_mat, &direct_material), "Hitable material identity");
    assert_no_rng_consumed("Hitable::Sphere", |rng| {
        let _ = hitable.ray_hit(&ray, scene::MIN_T, scene::MAX_T, rng);
    });

    // HitableList
    let (l_hit, l_mat) = list
        .ray_hit(&ray, scene::MIN_T, scene::MAX_T, &mut Xoshiro256Plus::seed_from_u64(2))
        .unwrap();
    assert_uv("HitableList", n, expected, (l_hit.u, l_hit.v));
    check_hit_geometry("HitableList", n, centre, radius, &l_hit);
    assert!(ptr::eq(l_mat, &direct_material), "HitableList material identity");
    assert_no_rng_consumed("HitableList", |rng| {
        let _ = list.ray_hit(&ray, scene::MIN_T, scene::MAX_T, rng);
    });
    assert_scalar_close("HitableList", n, "t vs Hitable", h_hit.t, l_hit.t);

    // BVH
    let (b_hit, b_mat) = bvh_root
        .ray_hit(&ray, scene::MIN_T, scene::MAX_T, &mut Xoshiro256Plus::seed_from_u64(3))
        .unwrap();
    assert_uv("BVH", n, expected, (b_hit.u, b_hit.v));
    check_hit_geometry("BVH", n, centre, radius, &b_hit);
    assert!(ptr::eq(b_mat, &direct_material), "BVH material identity");
    assert_no_rng_consumed("BVH", |rng| {
        let _ = bvh_root.ray_hit(&ray, scene::MIN_T, scene::MAX_T, rng);
    });
    assert_scalar_close("BVH", n, "t vs Hitable", h_hit.t, b_hit.t);

    // SpheresSoA scalar backend
    let (s_hit, s_mat) = soa.hit_scalar(&ray, scene::MIN_T, scene::MAX_T).unwrap();
    assert_uv("SpheresSoA::hit_scalar", n, expected, (s_hit.u, s_hit.v));
    check_hit_geometry("SpheresSoA::hit_scalar", n, centre, radius, &s_hit);
    assert!(ptr::eq(s_mat, &direct_material), "SpheresSoA material identity");
    assert_scalar_close("SpheresSoA", n, "t vs Hitable", h_hit.t, s_hit.t);

    // SpheresSoA default dispatch (AVX2/SSE4.1 on x86, scalar fallback elsewhere).
    let (d_hit, d_mat) = soa.ray_hit(&ray, scene::MIN_T, scene::MAX_T).unwrap();
    assert_uv("SpheresSoA::ray_hit", n, expected, (d_hit.u, d_hit.v));
    check_hit_geometry("SpheresSoA::ray_hit", n, centre, radius, &d_hit);
    assert!(ptr::eq(d_mat, &direct_material), "SpheresSoA default material identity");
    assert_scalar_close("SpheresSoA", n, "t vs Hitable", h_hit.t, d_hit.t);

    // ---------------------------------------------------------------------------------
    // 4. Two instances sharing one material: UV is computed in local space, so rigid
    //    rotation/translation (and uniform positive scaling) preserve it.
    // ---------------------------------------------------------------------------------
    let local_sphere = Sphere::new(Vec3::ZERO, 1.0);
    let local_hitable = Hitable::Sphere(&local_sphere, &direct_material);
    let local_n = vec3(0.3, 0.4, -0.5).normalize();
    let local_ray = ray_for_local_direction(local_n, 0.5);
    let (local_hit, local_mat) = local_hitable
        .ray_hit(
            &local_ray,
            scene::MIN_T,
            scene::MAX_T,
            &mut Xoshiro256Plus::seed_from_u64(4),
        )
        .unwrap();
    let local_expected = reference_uv(local_n);
    assert_uv("local sphere", local_n, local_expected, (local_hit.u, local_hit.v));
    assert!(ptr::eq(local_mat, &direct_material));

    let transforms = [
        Affine3A::from_rotation_translation(
            Quat::from_rotation_y(0.7),
            vec3(2.0, -1.0, 0.5),
        ),
        Affine3A::from_rotation_translation(
            Quat::from_rotation_x(-0.4) * Quat::from_rotation_z(0.9),
            vec3(-3.0, 2.0, 1.0),
        ) * Affine3A::from_scale(vec3(1.7, 1.7, 1.7)),
    ];

    for (index, transform) in transforms.iter().enumerate() {
        let instance = Instance::new(local_hitable, *transform);
        // Map the local ray into the instance's world and let Instance map it back.
        let world_ray = Ray::new(
            transform.transform_point3(local_ray.origin),
            transform.transform_vector3(local_ray.direction),
            local_ray.time,
        );
        let (hit, material) = instance
            .ray_hit(
                &world_ray,
                scene::MIN_T,
                scene::MAX_T,
                &mut Xoshiro256Plus::seed_from_u64(5 + index as u64),
            )
            .unwrap();
        let label = format!("Instance {}", index);
        assert_uv(&label, local_n, local_expected, (hit.u, hit.v));
        assert!(
            ptr::eq(material, &direct_material),
            "{} must share the material",
            label
        );

        // The world-space hit point maps back to the local point, and the texture sample
        // is exactly the one for the local direction.
        let local_point = transform.inverse().transform_point3(hit.point);
        check_hit_geometry(&label, local_n, Vec3::ZERO, 1.0, &RayHit {
            point: local_point,
            normal: transform.inverse().transform_vector3(hit.normal).normalize(),
            t: hit.t,
            u: hit.u,
            v: hit.v,
        });
        if texel_boundary_is_stable(local_expected.0, local_expected.1) {
            assert_color(
                &label,
                local_n,
                expected_color(local_expected.0, local_expected.1),
                direct_material.emitted(hit.u, hit.v, hit.point),
            );
        }
    }

    // ---------------------------------------------------------------------------------
    // 5. Material branches no longer decide whether UV exists: constants, nested Checker
    //    images and emissive images all receive the geometric UV. Programmatic noise
    //    textures still read the world point and ignore UV.
    // ---------------------------------------------------------------------------------
    let constant_tex = texture::constant(vec3(0.2, 0.4, 0.6));
    let constant_material = material::diffuse_light(&constant_tex);
    let constant_hitable = Hitable::Sphere(&unit, &constant_material);
    let oblique = vec3(0.3, 0.4, -0.5).normalize();
    let oblique_ray = ray_for_local_direction(oblique, 0.5);
    let (constant_hit, _) = constant_hitable
        .ray_hit(
            &oblique_ray,
            scene::MIN_T,
            scene::MAX_T,
            &mut Xoshiro256Plus::seed_from_u64(6),
        )
        .unwrap();
    assert_uv(
        "constant material",
        oblique,
        reference_uv(oblique),
        (constant_hit.u, constant_hit.v),
    );
    assert_vec_close(
        "constant material",
        oblique,
        "constant emitted value",
        vec3(0.2, 0.4, 0.6),
        constant_material.emitted(constant_hit.u, constant_hit.v, constant_hit.point),
    );

    let inner_checker = texture::checker(&tex, &tex);
    let outer_checker = texture::checker(&inner_checker, &inner_checker);
    let nested_material = material::diffuse_light(&outer_checker);
    let nested_hitable = Hitable::Sphere(&unit, &nested_material);
    let (nested_hit, nested_mat) = nested_hitable
        .ray_hit(
            &oblique_ray,
            scene::MIN_T,
            scene::MAX_T,
            &mut Xoshiro256Plus::seed_from_u64(7),
        )
        .unwrap();
    assert_uv(
        "two-level Checker image",
        oblique,
        reference_uv(oblique),
        (nested_hit.u, nested_hit.v),
    );
    assert!(ptr::eq(nested_mat, &nested_material));
    let nested_expected = reference_uv(oblique);
    assert_color(
        "two-level Checker image",
        oblique,
        expected_color(nested_expected.0, nested_expected.1),
        nested_material.emitted(nested_hit.u, nested_hit.v, nested_hit.point),
    );

    let mut perlin_rng = Xoshiro256Plus::seed_from_u64(8);
    let perlin = perlin::Perlin::new(&mut perlin_rng);
    let noise_tex = texture::noise(&perlin, 4.0);
    let world_point = vec3(0.25, -0.5, 1.25);
    assert_eq!(
        noise_tex.value(0.125, 0.875, world_point),
        noise_tex.value(0.875, 0.125, world_point),
        "programmatic noise textures must continue to read the world point, not UV"
    );

    // ---------------------------------------------------------------------------------
    // 6. Real `Scene.update` renders: direct emissive image vs the same image nested in
    //    two Checker levels, byte-identical pixels, and colors at the documented u/v
    //    positions.
    // ---------------------------------------------------------------------------------
    let params = params::Params {
        width: 64,
        height: 64,
        samples: 1,
        max_depth: 0,
        random_seed: false,
        use_bvh: false,
        soa: params::SoaMode::Off,
    };

    // Azimuths chosen away from the 4-column boundaries: u = 0.375, 0.625 and 0.875.
    // Latitudes give v = 0.6667 (top row) and v = 0.3333 (bottom row).
    let render_cases = [
        ("uv_0375_0667", vec3(0.612_372_36, 0.5, 0.612_372_36)),
        ("uv_0625_0667", vec3(0.612_372_36, 0.5, -0.612_372_36)),
        ("uv_0875_0333", vec3(-0.612_372_36, -0.5, -0.612_372_36)),
    ];

    let render_sphere = Sphere::new(Vec3::ZERO, 2.0);
    for (label, direction) in render_cases {
        let (direct, nested, cam) =
            render_direct_and_nested(&img, direction, &params, &out_dir, label);

        assert_eq!(
            direct.as_slice(),
            nested.as_slice(),
            "direct emissive image and nested Checker image renders must match ({})",
            label
        );

        // Reproduce every primary ray with the same per-pixel seeding used by
        // `Scene::update`; use the hit geometry and the independent reference UV to
        // predict which texel must appear. This checks the whole UV -> texture -> Scene
        // pipeline without trusting the production UV values.
        let inv_nx = 1.0 / params.width as f32;
        let inv_ny = 1.0 / params.height as f32;
        for y in 0..params.height {
            for x in 0..params.width {
                let mut rng = Xoshiro256Plus::seed_from_u64(
                    (x as u64 * 1973 + y as u64 * 9277) | 1,
                );
                let u = (x as f32 + rng.random::<f32>()) * inv_nx;
                let v = (y as f32 + rng.random::<f32>()) * inv_ny;
                let ray = cam.get_ray(u, v, &mut rng);
                let Some(hit) = render_sphere.ray_hit(&ray, scene::MIN_T, scene::MAX_T) else {
                    continue;
                };
                let local_n = (hit.point - render_sphere.centre()) / render_sphere.radius();
                let uv = reference_uv(local_n);
                if !texel_boundary_is_stable(uv.0, uv.1) {
                    continue;
                }
                let idx = (y * params.width + x) as usize;
                let expected = expected_color(uv.0, uv.1);
                let actual = vec3(direct[idx].0, direct[idx].1, direct[idx].2);
                let delta = (actual - expected).length();
                if !delta.is_finite() || delta > 3.0e-6 {
                    panic!(
                        "sphere_uv_contract failure path=Scene.update render {} pixel=({}, {}) \
                         local_direction=({:.9}, {:.9}, {:.9}) expected_uv=({:.9}, {:.9}) \
                         expected_texel={:?} actual_texel={:?} delta={:.3e}",
                        label,
                        x,
                        y,
                        local_n.x,
                        local_n.y,
                        local_n.z,
                        uv.0,
                        uv.1,
                        expected,
                        actual,
                        delta
                    );
                }
            }
        }
    }

    println!(
        "sphere_uv_contract renders written to {}",
        out_dir.display()
    );
}
