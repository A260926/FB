const assert=require('node:assert/strict');
const nurbs=require('../nurbs');
const make=()=>nurbs({points:[[0,0],[1,2],[3,0]],weights:[1,2,1],degree:2,knots:[0,0,0,1,1,1],boundary:'clamped'});
const s=make();
const p=s.evaluate([],0.5);
assert.ok(Math.abs(p[0]-7/6)<1e-12 && Math.abs(p[1]-4/3)<1e-12);
const d=s.evaluator(1)([],.5);assert.ok(d.every(Number.isFinite));
const affine=[2,0,0, 0,3,0, 4,-2,1];
s.transform(affine);
const a=s.evaluate([],.5);
assert.ok(Math.abs(a[0]-(2*p[0]+4))<1e-12 && Math.abs(a[1]-(3*p[1]-2))<1e-12);
console.log('NURBS_AFFINE_OK',JSON.stringify(a));
const q=make();const project=[1,0,.2, 0,1,0, 0,0,1];
q.transform(project);
const actual=q.evaluate([],.5),expected=p.map(x=>x/(1+.2*p[0]));
const error=Math.hypot(...actual.map((x,i)=>x-expected[i]));
assert.ok(error>0.01);
console.log('NURBS_PROJECTIVE_GAP',error.toFixed(9));
console.log('BASELINE_NURBS_OK rational-evaluation-affine-and-projective-gap');
