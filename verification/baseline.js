'use strict';
const assert = require('node:assert/strict');
const JZZ = require('../javascript/JZZ.js');
const out=[];
const p=JZZ.M2M1();
p.connect(m=>out.push({bytes:Array.from(m),gr:m.gr}));
p.send(JZZ.UMP([0x42,0x93,60,0,0x80,0,0,0]));
p.send(JZZ.UMP([0x42,0x83,60,0,0x40,0,0,0]));
assert.equal(out.length,2);
assert.deepEqual(out[0],{bytes:[0x93,60,64],gr:2});
assert.deepEqual(out[1],{bytes:[0x83,60,32],gr:2});
p.send(JZZ.UMP([0x42,0x63,60,0,0xc0,0,0,0]));
assert.equal(out.length,2);
const zone=JZZ.MPE(0,2);
const n=JZZ.MIDI.noteOn(0,60,100);n._mpe=60;
assert.equal(zone.filter(n).getChannel(),1);
const off=JZZ.MIDI.noteOff(0,60);off._mpe=60;
assert.equal(zone.filter(off).getChannel(),1);
console.log('BASELINE_M2M1_NOTE_GROUP_PASS');
console.log('BASELINE_NATIVE_PERNOTE_PITCH_IGNORED');
console.log('BASELINE_MPE_ROUTE_PASS');
