// ---------------------------------------------------------------------------
// Shared sampling + skinning core (the single implementation of the classic
// animateiqm() math, used by both the serial entry and the async service).
// ---------------------------------------------------------------------------

bool sample_and_skin(const SkinSource &src, float curframe, const SkinDest &dst)
{
    if(src.numframes <= 0 || src.numjoints <= 0 || src.numverts < 0) return false;
    if(!src.frames || !src.joints || !dst.outframe) return false;
    if(!std::isfinite(curframe)) return false;

    // Frame numbers are finite floats and loop with a positive modulo over
    // the whole animation frame array, so negative frames wrap around.
    const double floored = floor((double)curframe);
    const float frameoffset = (float)((double)curframe - floored);
    double wrapped = fmod(floored, (double)src.numframes);
    if(wrapped < 0) wrapped += src.numframes;
    const int frame1 = (int)wrapped;
    const int frame2 = frame1 + 1 < src.numframes ? frame1 + 1 : 0;

    const Matrix3x4 *mat1 = &src.frames[frame1 * src.numjoints],
                    *mat2 = &src.frames[frame2 * src.numjoints];
    // Interpolate matrixes between the two closest frames and concatenate with parent matrix if necessary.
    // Concatenate the result with the inverse of the base pose.
    // You would normally do animation blending and inter-frame blending here in a 3D engine.
    for(int i = 0; i < src.numjoints; i++)
    {
        Matrix3x4 mat = mat1[i]*(1 - frameoffset) + mat2[i]*frameoffset;
        if(src.joints[i].parent >= 0) dst.outframe[i] = dst.outframe[src.joints[i].parent] * mat;
        else dst.outframe[i] = mat;
    }
    // The actual vertex generation based on the matrixes follows...
    const Vec3 *srcpos = (const Vec3 *)src.inposition, *srcnorm = (const Vec3 *)src.innormal;
    const Vec4 *srctan = (const Vec4 *)src.intangent;
    Vec3 *dstpos = (Vec3 *)dst.outposition, *dstnorm = (Vec3 *)dst.outnormal,
         *dsttan = (Vec3 *)dst.outtangent, *dstbitan = (Vec3 *)dst.outbitangent;
    const uchar *index = src.inblendindex, *weight = src.inblendweight;
    for(int i = 0; i < src.numverts; i++)
    {
        // Blend matrixes for this vertex according to its blend weights.
        // the first index/weight is always present, and the weights are
        // guaranteed to add up to 255. So if only the first weight is
        // presented, you could optimize this case by skipping any weight
        // multiplies and intermediate storage of a blended matrix.
        // There are only at most 4 weights per vertex, and they are in
        // sorted order from highest weight to lowest weight. Weights with
        // 0 values, which are always at the end, are unused.
        Matrix3x4 mat = dst.outframe[index[0]] * (weight[0]/255.0f);
        for(int j = 1; j < 4 && weight[j]; j++)
            mat += dst.outframe[index[j]] * (weight[j]/255.0f);

        // Transform attributes by the blended matrix.
        // Position uses the full 3x4 transformation matrix.
        // Normals and tangents only use the 3x3 rotation part
        // of the transformation matrix.
        *dstpos = mat.transform(*srcpos);

        // Note that if the matrix includes non-uniform scaling, normal vectors
        // must be transformed by the inverse-transpose of the matrix to have the
        // correct relative scale. Note that invert(mat) = adjoint(mat)/determinant(mat),
        // and since the absolute scale is not important for a vector that will later
        // be renormalized, the adjoint-transpose matrix will work fine, which can be
        // cheaply generated by 3 cross-products.
        //
        // If you don't need to use joint scaling in your models, you can simply use the
        // upper 3x3 part of the position matrix instead of the adjoint-transpose shown
        // here.
        Matrix3x3 matnorm(mat.b.cross3(mat.c), mat.c.cross3(mat.a), mat.a.cross3(mat.b));

        *dstnorm = matnorm.transform(*srcnorm);
        // Note that input tangent data has 4 coordinates,
        // so only transform the first 3 as the tangent vector.
        *dsttan = matnorm.transform(Vec3(*srctan));
        // Note that bitangent = cross(normal, tangent) * sign,
        // where the sign is stored in the 4th coordinate of the input tangent data.
        *dstbitan = dstnorm->cross(*dsttan) * srctan->w;

        srcpos++;
        srcnorm++;
        srctan++;
        dstpos++;
        dstnorm++;
        dsttan++;
        dstbitan++;

        index += 4;
        weight += 4;
    }
    return true;
}

// ---------------------------------------------------------------------------
// PoseAsset loading.  The asset copies every array it needs out of the file
// buffer; once load_pose_asset returns, nothing borrows that buffer.
// ---------------------------------------------------------------------------

SkinSource PoseAsset::skin_source() const
{
    SkinSource src;
    src.frames = frames.data();
    src.numframes = frames_;
    src.joints = joints.data();
    src.numjoints = joints_;
    src.inposition = position.data();
    src.innormal = normal.data();
    src.intangent = tangent.data();
    src.inblendindex = blendindex.data();
    src.inblendweight = blendweight.data();
    src.numverts = verts_;
    return src;
}

