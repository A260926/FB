import './historical-baseline.mjs';
import assert from 'node:assert/strict';
import { BufferGeometry } from '../src/core/BufferGeometry.js';
import { Float32BufferAttribute, Uint16BufferAttribute, Uint8BufferAttribute } from '../src/core/BufferAttribute.js';
import { Bone } from '../src/objects/Bone.js';
import { Skeleton } from '../src/objects/Skeleton.js';
import { SkinnedMesh } from '../src/objects/SkinnedMesh.js';
import { Matrix4 } from '../src/math/Matrix4.js';
