#!/bin/bash
# baseline/run.sh — observe the two floor 0 deviations at the starting point.
#
#   1. Bark map: with 48 kHz, 32 spectral bins and a 64-entry Bark map, the
#      first non-zero bin (750 Hz) must land in map entry 16.
#   2. LSP recovery: a one-dimensional codebook returning 0.2 three times in
#      an order-3 floor must accumulate to 0.2, 0.4, 0.6.
#
# The observed values are printed and preserved in baseline/record.txt.
# With REQUIRE_CORRECT_FLOOR0=1 the deviations are reported as test failures
# (exit status non-zero).
set -o pipefail
cd "$(dirname "$0")/.."

tmp="floor0_baseline_observe_test.go"
trap 'rm -f "$tmp"' EXIT

cat > "$tmp" <<'EOF'
package vorbis

// This file is generated by baseline/run.sh and removed when it exits.

import (
	"os"
	"testing"
)

// observeWriter packs bits LSB-first (the Vorbis bit order).
type observeWriter struct {
	out []byte
	acc uint64
	n   uint
}

func (w *observeWriter) write(v uint64, bits uint) {
	w.acc |= (v & ((1 << bits) - 1)) << w.n
	w.n += bits
	for w.n >= 8 {
		w.out = append(w.out, byte(w.acc))
		w.acc >>= 8
		w.n -= 8
	}
}

func (w *observeWriter) bytes() []byte {
	if w.n > 0 {
		return append(w.out, byte(w.acc))
	}
	return w.out
}

func TestFloor0BaselineObservation(t *testing.T) {
	// Deviation 1: position of the first non-zero bin in the Bark map.
	// 48 kHz, 32 spectral bins, 64 map entries: bin 1 is 750 Hz, which
	// belongs to map entry 16.
	f := &floor0{rate: 48000, barkMapSize: 64}
	map1 := f.mapResult(1, 32)
	t.Logf("floor0-baseline: map1=%d want=16", map1)

	// Deviation 2: cumulative LSP recovery. A one-dimensional codebook
	// returning 0.2 three times must accumulate to 0.2, 0.4, 0.6.
	// The book has two entries with one-bit codewords (tree: entry 0 on a
	// zero bit, entry 1 on a one bit); only entry 0 (value 0.2) is read.
	book := codebook{
		dimensions: 1,
		values:     []float32{0.2, 0.2},
		entries:    &huffmanCode{tree: []uint32{1, 3}},
	}
	w := &observeWriter{}
	w.write(32, 6) // amplitude
	w.write(0, 1)  // book number
	w.write(0, 1)  // three codewords, all entry 0
	w.write(0, 1)
	w.write(0, 1)
	f0 := &floor0{order: 3, amplitudeBits: 6, amplitudeOffset: 50, bookList: []uint8{0}}
	data := f0.Decode(newBitReader(w.bytes()), []codebook{book}, 16).(floor0Data)
	t.Logf("floor0-baseline: lsp=%.6g want=[0.2 0.4 0.6]", data.coefficients)

	if os.Getenv("REQUIRE_CORRECT_FLOOR0") == "1" {
		if map1 != 16 {
			t.Errorf("map1=%d, want 16", map1)
		}
		want := []float32{0.2, 0.4, 0.6}
		for i, c := range data.coefficients {
			if c != want[i] {
				t.Errorf("coefficient %d = %v, want %v (cumulative LSP)", i, c, want[i])
			}
		}
	}
}
EOF

go test -count=1 -run '^TestFloor0BaselineObservation$' -v . 2>&1 | tee baseline/record.txt
