// ReloadRequest describes a blocking reload request generated by Plan.
type ReloadRequest struct {
	Token uint64
	URL   string
	MSN   uint64
	Part  *uint64
}

// ReloadSync coordinates reload requests between renditions of a low latency
// HLS stream. It is an in-memory state holder: it never performs network
// requests and does not implement blocking itself.
type ReloadSync struct {
	snapshots map[string]*reloadSnapshot
	pending   map[string]*reloadPending // keyed by target URI
	tokens    map[uint64]string         // token -> target URI
	nextToken uint64
	revision  uint64
}

type reloadSnapshot struct {
	playlist *MediaPlaylist
	revision uint64
}

type reloadPending struct {
	token     uint64
	sourceURI string
	targetURI string
	msn       uint64
	part      *uint64
	sourceRev uint64
	targetRev uint64
}

// NewReloadSync creates an empty reload coordinator.
func NewReloadSync() *ReloadSync {
	return &ReloadSync{
		snapshots: make(map[string]*reloadSnapshot),
		pending:   make(map[string]*reloadPending),
		tokens:    make(map[uint64]string),
	}
}

// Update stores a deep copy of the playlist for the given absolute http/https
// URI. Later changes to the caller's playlist or its encoding cache do not
// affect the coordinator.
func (r *ReloadSync) Update(uri string, p *MediaPlaylist) error {
	if err := validateReloadURI(uri); err != nil {
		return err
	}
	if p == nil {
		return errors.New("reload: nil playlist")
	}
	r.revision++
	if r.revision == 0 { // revision wrapped, keep it usable
		r.revision = 1
	}
	r.snapshots[uri] = &reloadSnapshot{
		playlist: cloneMediaPlaylist(p),
		revision: r.revision,
	}
	return nil
}

// Plan produces a blocking reload request for targetURI using the rendition
// report found in the source snapshot. It fails without changing any state if
// either snapshot is missing, the target does not announce blocking reload
// support, or the source does not contain exactly one report for the target.
func (r *ReloadSync) Plan(sourceURI, targetURI string) (ReloadRequest, error) {
	var zero ReloadRequest
	if err := validateReloadURI(sourceURI); err != nil {
		return zero, err
	}
	if err := validateReloadURI(targetURI); err != nil {
		return zero, err
	}
	source := r.snapshots[sourceURI]
	if source == nil {
		return zero, fmt.Errorf("reload: no snapshot for source %q", sourceURI)
	}
	target := r.snapshots[targetURI]
	if target == nil {
		return zero, fmt.Errorf("reload: no snapshot for target %q", targetURI)
	}
	if _, busy := r.pending[targetURI]; busy {
		return zero, fmt.Errorf("reload: target %q already has a pending request", targetURI)
	}
	if !target.playlist.CanBlockReload {
		return zero, fmt.Errorf("reload: target %q does not support blocking reload", targetURI)
	}

	report, err := findReport(source.playlist, sourceURI, targetURI)
	if err != nil {
		return zero, err
	}

	msn, part, err := resolveReportPosition(source.playlist, report)
	if err != nil {
		return zero, err
	}

	// Advance to the position the target should fetch next.
	if part != nil {
		next, ok := addUint64(*part, 1)
		if !ok {
			return zero, errors.New("reload: part index overflow")
		}
		part = &next
	} else {
		next, ok := addUint64(msn, 1)
		if !ok {
			return zero, errors.New("reload: media sequence number overflow")
		}
		msn = next
	}

	// Merge with what the target already knows it has locally.
	localMSN, localPart, err := targetLocalPosition(target.playlist)
	if err != nil {
		return zero, err
	}
	if comparePositions(localMSN, localPart, msn, part) > 0 {
		msn, part = localMSN, localPart
	}

	requestURL, err := buildReloadURL(targetURI, msn, part)
	if err != nil {
		return zero, err
	}

	if r.nextToken == math.MaxUint64 {
		return zero, errors.New("reload: token space exhausted")
	}
	r.nextToken++
	token := r.nextToken
	if token == 0 {
		return zero, errors.New("reload: invalid token")
	}

	partCopy := cloneUint64(part)
	r.pending[targetURI] = &reloadPending{
		token:     token,
		sourceURI: sourceURI,
		targetURI: targetURI,
		msn:       msn,
		part:      partCopy,
		sourceRev: source.revision,
		targetRev: target.revision,
	}
	r.tokens[token] = targetURI

	return ReloadRequest{Token: token, URL: requestURL, MSN: msn, Part: cloneUint64(part)}, nil
}

// Commit finalizes a pending request. It succeeds only when the supplied
// response playlist proves that the requested position has actually been
// published. On success the target snapshot is replaced and the pending
// request released; on any error nothing changes.
func (r *ReloadSync) Commit(token uint64, p *MediaPlaylist) error {
	targetURI, ok := r.tokens[token]
	if !ok {
		return fmt.Errorf("reload: unknown token %d", token)
	}
	pending := r.pending[targetURI]
	if pending == nil || pending.token != token {
		return fmt.Errorf("reload: token %d is not the active request", token)
	}
	if p == nil {
		return errors.New("reload: commit requires a response playlist")
	}
	src := r.snapshots[pending.sourceURI]
	tgt := r.snapshots[pending.targetURI]
	if src == nil || tgt == nil {
		return fmt.Errorf("reload: token %d is stale", token)
	}
	if src.revision != pending.sourceRev || tgt.revision != pending.targetRev {
		return fmt.Errorf("reload: token %d is stale", token)
	}
	if !publishedAt(p, pending.msn, pending.part) {
		return fmt.Errorf("reload: requested position msn=%d part=%v was not published", pending.msn, formatPart(pending.part))
	}

	r.revision++
	if r.revision == 0 {
		r.revision = 1
	}
	r.snapshots[targetURI] = &reloadSnapshot{
		playlist: cloneMediaPlaylist(p),
		revision: r.revision,
	}
	delete(r.pending, targetURI)
	delete(r.tokens, token)
	return nil
}

// Abort cancels the pending request for the given active token. An active but
// stale token may be aborted so that a fresh Plan can be issued; a token that
// no longer owns a pending request is rejected.
func (r *ReloadSync) Abort(token uint64) error {
	targetURI, ok := r.tokens[token]
	if !ok {
		return fmt.Errorf("reload: unknown token %d", token)
	}
	pending := r.pending[targetURI]
	if pending == nil || pending.token != token {
		return fmt.Errorf("reload: token %d is not the active request", token)
	}
	delete(r.pending, targetURI)
	delete(r.tokens, token)
	return nil
}

// validateReloadURI checks that the URI is an absolute http/https URL without
// a fragment.
func validateReloadURI(raw string) error {
	u, err := url.Parse(raw)
	if err != nil {
		return fmt.Errorf("reload: invalid URI %q: %w", raw, err)
	}
	if !u.IsAbs() || u.Host == "" {
		return fmt.Errorf("reload: URI %q must be absolute", raw)
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return fmt.Errorf("reload: URI %q must use http or https", raw)
	}
	if u.Fragment != "" || u.RawFragment != "" {
		return fmt.Errorf("reload: URI %q must not contain a fragment", raw)
	}
	return nil
}

// findReport returns the single rendition report in the source playlist that
// resolves to the target URL. Two reports that resolve to the same target are
// reported as a conflict.
func findReport(source *MediaPlaylist, sourceURI, targetURI string) (RenditionReport, error) {
	base, err := url.Parse(sourceURI)
	if err != nil {
		return RenditionReport{}, err
	}
	var (
		found   RenditionReport
		matches int
	)
	for _, report := range source.RenditionReports {
		rel, err := url.Parse(report.URI)
		if err != nil {
			continue
		}
		resolved := base.ResolveReference(rel)
		if resolved.String() != targetURI {
			continue
		}
		matches++
		if matches == 1 {
			found = report
		}
	}
	if matches == 0 {
		return RenditionReport{}, fmt.Errorf("reload: no rendition report points to %q", targetURI)
	}
	if matches > 1 {
		return RenditionReport{}, fmt.Errorf("reload: conflicting rendition reports point to %q", targetURI)
	}
	return found, nil
}

// resolveReportPosition determines the media sequence number and part index
// the report refers to. Follows the task's derivation rules for omitted
// LAST-MSN and LAST-PART attributes.
func resolveReportPosition(source *MediaPlaylist, report RenditionReport) (uint64, *uint64, error) {
	var msn uint64
	if report.LastMSN != nil {
		msn = *report.LastMSN
	} else {
		derived, ok := deriveMSN(source)
		if !ok {
			return 0, nil, errors.New("reload: source playlist has no media content to derive a position from")
		}
		msn = derived
	}

	part := cloneUint64(report.LastPart)
	if part == nil {
		if parts, _ := partsForMSN(source, msn); len(parts) > 0 {
			idx := uint64(len(parts) - 1)
			part = &idx
		}
	}
	return msn, part, nil
}

// deriveMSN returns the last media sequence number containing parts, or the
// last complete segment's sequence number when no parts exist.
func deriveMSN(p *MediaPlaylist) (uint64, bool) {
	if p.Count() == 0 && len(p.TrailingParts) == 0 {
		return 0, false
	}
	segments := orderedSegments(p)
	var (
		last  uint64
		found bool
	)
	for _, seg := range segments {
		if len(seg.Parts) > 0 {
			last = seg.SeqId
			found = true
		}
	}
	if len(p.TrailingParts) > 0 {
		if msn, ok := trailingMSN(p); ok {
			last = msn
			found = true
		}
	}
	if found {
		return last, true
	}
	if len(segments) == 0 {
		return 0, false
	}
	return segments[len(segments)-1].SeqId, true
}

// trailingMSN returns the media sequence number belonging to the trailing
// parts (the next segment that has not been completed yet).
func trailingMSN(p *MediaPlaylist) (uint64, bool) {
	segments := orderedSegments(p)
	if len(segments) == 0 {
		if len(p.TrailingParts) == 0 {
			return 0, false
		}
		return p.SeqNo, true
	}
	return addUint64(segments[len(segments)-1].SeqId, 1)
}

// partsForMSN returns the parts published for the given sequence number and
// whether a complete segment at that sequence number exists.
func partsForMSN(p *MediaPlaylist, msn uint64) ([]Part, bool) {
	for _, seg := range orderedSegments(p) {
		if seg.SeqId == msn {
			return seg.Parts, true
		}
	}
	if len(p.TrailingParts) > 0 {
		if tm, ok := trailingMSN(p); ok && tm == msn {
			return p.TrailingParts, false
		}
	}
	return nil, false
}

// targetLocalPosition reports the target's locally known next download
// position. When trailing parts exist the next part index is one past the
// last published part.
func targetLocalPosition(p *MediaPlaylist) (uint64, *uint64, error) {
	msn, ok := addUint64(p.SeqNo, uint64(p.Count()))
	if !ok {
		return 0, nil, errors.New("reload: media sequence number overflow")
	}
	if len(p.TrailingParts) > 0 {
		part := uint64(len(p.TrailingParts))
		return msn, &part, nil
	}
	return msn, nil, nil
}

// publishedAt reports whether the response playlist shows the requested
// position as published.
func publishedAt(response *MediaPlaylist, msn uint64, part *uint64) bool {
	parts, complete := partsForMSN(response, msn)
	if complete {
		return true
	}
	if len(parts) == 0 {
		return false
	}
	if part == nil {
		return true
	}
	return uint64(len(parts)) > *part
}

// comparePositions orders two (msn, part) positions. Within the same media
// sequence number a nil part sorts before any concrete part index.
func comparePositions(msnA uint64, partA *uint64, msnB uint64, partB *uint64) int {
	if msnA < msnB {
		return -1
	}
	if msnA > msnB {
		return 1
	}
	switch {
	case partA == nil && partB == nil:
		return 0
	case partA == nil:
		return -1
	case partB == nil:
		return 1
	case *partA < *partB:
		return -1
	case *partA > *partB:
		return 1
	default:
		return 0
	}
}

func buildReloadURL(targetURI string, msn uint64, part *uint64) (string, error) {
	u, err := url.Parse(targetURI)
	if err != nil {
		return "", err
	}
	q := u.Query()
	q.Set("_HLS_msn", strconv.FormatUint(msn, 10))
	if part != nil {
		q.Set("_HLS_part", strconv.FormatUint(*part, 10))
	} else {
		q.Del("_HLS_part")
	}
	u.RawQuery = q.Encode()
	return u.String(), nil
}

func addUint64(a, b uint64) (uint64, bool) {
	if a > math.MaxUint64-b {
		return 0, false
	}
	return a + b, true
}

func cloneUint64(v *uint64) *uint64 {
	if v == nil {
		return nil
	}
	c := *v
	return &c
}

func formatPart(part *uint64) string {
	if part == nil {
		return "none"
	}
	return strconv.FormatUint(*part, 10)
}

// orderedSegments returns the segments in playback order, following the
// playlist's ring buffer from head.
func orderedSegments(p *MediaPlaylist) []*MediaSegment {
	if p.Count() == 0 || p.capacity == 0 {
		return nil
	}
	out := make([]*MediaSegment, 0, p.Count())
	idx := p.head
	for i := uint(0); i < p.Count(); i++ {
		seg := p.Segments[idx]
		idx = (idx + 1) % p.capacity
		if seg != nil {
			out = append(out, seg)
		}
	}
	return out
}

// cloneMediaPlaylist performs a deep copy so callers may keep mutating their
// own playlist, including its encoding cache.
func cloneMediaPlaylist(p *MediaPlaylist) *MediaPlaylist {
	if p == nil {
		return nil
	}
	cp := *p
	cp.buf = bytes.Buffer{}
	if p.Segments != nil {
		cp.Segments = make([]*MediaSegment, len(p.Segments))
		for i, seg := range p.Segments {
			if seg == nil {
				continue
			}
			cp.Segments[i] = cloneMediaSegment(seg)
		}
	}
	if p.TrailingParts != nil {
		cp.TrailingParts = append([]Part(nil), p.TrailingParts...)
	}
	if p.RenditionReports != nil {
		cp.RenditionReports = make([]RenditionReport, len(p.RenditionReports))
		for i, report := range p.RenditionReports {
			cp.RenditionReports[i] = RenditionReport{
				URI:      report.URI,
				LastMSN:  cloneUint64(report.LastMSN),
				LastPart: cloneUint64(report.LastPart),
			}
		}
	}
	if p.Key != nil {
		key := *p.Key
		cp.Key = &key
	}
	if p.Map != nil {
		m := *p.Map
		cp.Map = &m
	}
	if p.WV != nil {
		wv := *p.WV
		cp.WV = &wv
	}
	if p.Custom != nil {
		cp.Custom = make(map[string]CustomTag, len(p.Custom))
		for k, v := range p.Custom {
			cp.Custom[k] = v
		}
	}
	if p.customDecoders != nil {
		cp.customDecoders = append([]CustomDecoder(nil), p.customDecoders...)
	}
	return &cp
}

func cloneMediaSegment(s *MediaSegment) *MediaSegment {
	cp := *s
	if s.Parts != nil {
		cp.Parts = append([]Part(nil), s.Parts...)
	}
	if s.Key != nil {
		key := *s.Key
		cp.Key = &key
	}
	if s.Map != nil {
		m := *s.Map
		cp.Map = &m
	}
	if s.SCTE != nil {
		scte := *s.SCTE
		cp.SCTE = &scte
	}
	if s.Custom != nil {
		cp.Custom = make(map[string]CustomTag, len(s.Custom))
		for k, v := range s.Custom {
			cp.Custom[k] = v
		}
	}
	return &cp
}

