/*

Headless ViewLod demonstration: no SDL, window or GPU required.

Three camera positions drive one ViewLod over an off-centre closed sphere.
The near camera keeps the fine unit-cell geometry, an intermediate camera
sits inside the hysteresis band, and the far camera collapses most of the
tree.  The near and far meshes are written as Wavefront OBJ files; the tests
consume both files and check that the far mesh really is coarser.

*/

#include "view_lod.h"

#include <glm/glm.hpp>

#include <cstdio>
#include <fstream>
#include <string>
#include <vector>

namespace
{

const glm::ivec3	GRID_MIN(-8, -8, -8);
const int			GRID_SIZE = 16;
const glm::vec3		SPHERE_CENTRE(2.f, 2.f, 3.f);
const float			SPHERE_RADIUS = 6.f;

float sphereDensity(const glm::vec3& p)
{
	return glm::length(p - SPHERE_CENTRE) - SPHERE_RADIUS;
}

// ----------------------------------------------------------------------------

LodCamera makeCamera(const glm::vec3& eye, float focalPixels, float nearDistance)
{
	LodCamera camera;
	camera.eye = eye;
	camera.forward = glm::normalize(SPHERE_CENTRE - eye);

	const glm::vec3 worldUp(0.f, 1.f, 0.f);
	camera.right = glm::normalize(glm::cross(camera.forward, worldUp));
	camera.up = glm::cross(camera.right, camera.forward);
	camera.focalPixels = focalPixels;
	camera.nearDistance = nearDistance;
	return camera;
}

// ----------------------------------------------------------------------------

bool writeObj(const std::string& path, const VertexBuffer& vertices, const IndexBuffer& indices)
{
	std::ofstream out(path);
	if (!out)
	{
		return false;
	}

	out << "# generated by examples/view_lod_headless.cpp\n";
	for (const MeshVertex& vertex : vertices)
	{
		out << "v " << vertex.xyz.x << ' ' << vertex.xyz.y << ' ' << vertex.xyz.z << '\n';
	}
	for (const MeshVertex& vertex : vertices)
	{
		out << "vn " << vertex.normal.x << ' ' << vertex.normal.y << ' ' << vertex.normal.z << '\n';
	}

	for (size_t i = 0; i + 2 < indices.size(); i += 3)
	{
		// OBJ indices are 1-based; vertices and normals share an ordering
		out << "f "
		    << indices[i] + 1 << "//" << indices[i] + 1 << ' '
		    << indices[i + 1] + 1 << "//" << indices[i + 1] + 1 << ' '
		    << indices[i + 2] + 1 << "//" << indices[i + 2] + 1 << '\n';
	}

	return static_cast<bool>(out);
}

} // namespace

// ----------------------------------------------------------------------------

int main()
{
	ViewLod lod(GRID_MIN, GRID_SIZE, sphereDensity);

	const float collapsePixels = 25.f;
	const float splitPixels = 70.f;

	struct Viewpoint
	{
		const char*	name;
		glm::vec3	eye;
	};

	const Viewpoint viewpoints[] =
	{
		{ "near", SPHERE_CENTRE + glm::vec3(10.f, 3.f, 4.f) },
		{ "mid",  SPHERE_CENTRE + glm::vec3(35.f, 12.f, 18.f) },
		{ "far",  SPHERE_CENTRE + glm::vec3(140.f, 60.f, 90.f) },
	};

	size_t nearTriangles = 0;
	size_t farTriangles = 0;

	for (const Viewpoint& viewpoint : viewpoints)
	{
		const LodCamera camera = makeCamera(viewpoint.eye, 500.f, 0.5f);
		lod.update(camera, collapsePixels, splitPixels);

		VertexBuffer vertices;
		IndexBuffer indices;
		lod.mesh(vertices, indices);

		const LodStats& stats = lod.lastStats();
		std::printf("view=%s frontier=%zu vertices=%zu triangles=%zu "
		            "errorTests=%zu balanceSplits=%zu\n",
		            viewpoint.name, lod.frontier().size(), vertices.size(),
		            indices.size() / 3, stats.errorTests, stats.balanceSplits);

		if (std::string(viewpoint.name) == "near")
		{
			nearTriangles = indices.size() / 3;
			if (!writeObj(".task-build/lod-near.obj", vertices, indices))
			{
				std::fprintf(stderr, "failed to write lod-near.obj\n");
				return 1;
			}
		}
		else if (std::string(viewpoint.name) == "far")
		{
			farTriangles = indices.size() / 3;
			if (!writeObj(".task-build/lod-far.obj", vertices, indices))
			{
				std::fprintf(stderr, "failed to write lod-far.obj\n");
				return 1;
			}
		}
	}

	std::printf("densityCalls=%zu nearTriangles=%zu farTriangles=%zu\n",
	            lod.lastStats().densityCalls, nearTriangles, farTriangles);

	if (nearTriangles == 0 || farTriangles == 0 || farTriangles >= nearTriangles)
	{
		std::fprintf(stderr, "unexpected triangle counts\n");
		return 2;
	}

	std::printf("VIEW_LOD_EXAMPLE_OK\n");
	return 0;
}
