"use strict"

// Generates a staircase voxel model, meshes it with the exact-AO path and
// writes an ASCII PLY whose vertex colours encode the ambient-occlusion
// intensity (the same byte the mesh stores per vertex).
//
// Run with: node examples/staircase.js [output.ply]

var fs = require("fs")
var path = require("path")
var ndarray = require("ndarray")
var mesh = require("../mesh")

var OPAQUE = 1 << 15
var N = 8 // core extent per axis

var vox = ndarray(new Uint16Array((N + 2) * (N + 2) * (N + 2)),
                  [N + 2, N + 2, N + 2])

// A staircase on top of a solid base platform.  The base fills the bottom
// layer of the whole core; its interior top faces share one constant AO value
// and are exactly mergeable into large rectangles, while the staircase above
// supplies non-constant, per-corner ambient occlusion.
for (var x = 0; x < N; ++x) {
  for (var z = 0; z < N; ++z) {
    // base platform: the bottom voxel of every column is solid
    vox.set(x + 1, 1, z + 1, OPAQUE | 1)
    // staircase rising along x on top of the base
    for (var y = 1; y <= x && y < N; ++y) {
      vox.set(x + 1, y + 1, z + 1, OPAQUE | 1)
    }
  }
}

var data = mesh.exactAO(vox)
if (!data) {
  throw new Error("staircase produced no faces")
}
var legacyData = mesh(vox)

var vertexCount = data.length / 8
var faceCount = vertexCount / 3 // every three vertices is one triangle
var lines = [
  "ply",
  "format ascii 1.0",
  "comment generated by examples/staircase.js (exact AO path)",
  "element vertex " + vertexCount,
  "property float x",
  "property float y",
  "property float z",
  "property uchar red",
  "property uchar green",
  "property uchar blue",
  "element face " + faceCount,
  "property list uchar int vertex_indices",
  "end_header"
]

for (var i = 0; i < data.length; i += 8) {
  var ao = data[i + 3]
  lines.push(data[i] + " " + data[i + 1] + " " + data[i + 2] + " " +
             ao + " " + ao + " " + ao)
}
for (var f = 0; f < vertexCount; f += 3) {
  lines.push("3 " + f + " " + (f + 1) + " " + (f + 2))
}

var out = process.argv[2] ||
  path.join(__dirname, "staircase.ply")
fs.writeFileSync(out, lines.join("\n") + "\n")
console.log("wrote " + out + " vertices=" + vertexCount + " faces=" + faceCount)
console.log("exact path " + vertexCount + " vertices vs legacy " +
  legacyData.length / 8 + " vertices")
