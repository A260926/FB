'use strict';

//
// Example: export CAD surfaces with polar (collapsed) edges as OBJ.
//
//   node examples/cad-poles.cjs <output-directory>
//
// Writes roundtop.obj (a closed dome with a pole at the top) and cone.obj (a
// closed cone with its apex as the pole).  Both use `extras/sample-cad.js`,
// which merges the pole row into a single shared position, fans the adjacent
// ring, and computes analytic limit normals at the pole.
//
// The OBJ files use shared `v` positions with per-corner `vt` / `vn` indices,
// matching the mesh layout returned by `sampleCad`:
//   f v/vt/vn v/vt/vn v/vt/vn
//

const fs = require('fs');
const path = require('path');
const nurbs = require('../nurbs');
const sampleCad = require('../extras/sample-cad');

const SQRT1_2 = Math.SQRT1_2;

// A periodic rational quadratic ring.  Simple knots keep the interior knot
// multiplicity at most degree - 1, which `sampleCad` validates.
function periodicRing (segments) {
  const points = [];
  const weights = [];
  const knots = [];
  for (let i = 0; i < segments; i++) {
    const angle = 2 * Math.PI * i / segments;
    points.push([Math.cos(angle), Math.sin(angle)]);
    weights.push(1);
  }
  for (let i = 0; i <= segments; i++) knots.push(i);
  return { points, weights, knots, boundary: 'closed' };
}

// Revolve a rational quadratic profile curve around the u axis.
// `profile` entries are [radius, height].
function revolve (ring, profilePoints, profileWeights, profileKnots) {
  const points = [];
  const weights = [];
  for (let i = 0; i < ring.points.length; i++) {
    const row = [];
    const wrow = [];
    for (let j = 0; j < profilePoints.length; j++) {
      const radius = profilePoints[j][0];
      row.push([
        ring.points[i][0] * radius,
        ring.points[i][1] * radius,
        profilePoints[j][1]
      ]);
      wrow.push(ring.weights[i] * profileWeights[j]);
    }
    points.push(row);
    weights.push(wrow);
  }
  return nurbs({
    points,
    weights,
    degree: [2, 2],
    boundary: ['closed', 'clamped'],
    knots: [ring.knots, profileKnots]
  });
}

function writeObj (file, mesh) {
  const lines = [];
  lines.push('# generated by examples/cad-poles.cjs');
  for (let i = 0; i < mesh.positions.length; i += 3) {
    lines.push('v ' + mesh.positions[i] + ' ' + mesh.positions[i + 1] + ' ' + mesh.positions[i + 2]);
  }
  for (let i = 0; i < mesh.cornerUVs.length; i += 2) {
    lines.push('vt ' + mesh.cornerUVs[i] + ' ' + mesh.cornerUVs[i + 1]);
  }
  for (let i = 0; i < mesh.cornerNormals.length; i += 3) {
    lines.push('vn ' + mesh.cornerNormals[i] + ' ' + mesh.cornerNormals[i + 1] + ' ' + mesh.cornerNormals[i + 2]);
  }
  const triangleCount = mesh.cells.length / 3;
  for (let t = 0; t < triangleCount; t++) {
    const corners = [];
    for (let c = 0; c < 3; c++) {
      const positionIndex = mesh.cells[3 * t + c] + 1;
      const cornerIndex = 3 * t + c + 1;
      corners.push(positionIndex + '/' + cornerIndex + '/' + cornerIndex);
    }
    lines.push('f ' + corners.join(' '));
  }
  fs.writeFileSync(file, lines.join('\n') + '\n');
}

function main () {
  const outputDirectory = process.argv[2];
  if (!outputDirectory) {
    console.error('usage: node examples/cad-poles.cjs <output-directory>');
    process.exit(2);
  }
  fs.mkdirSync(outputDirectory, { recursive: true });

  // Round dome: quarter-circle meridian, pole at the top (v = vmax).
  const domeRing = periodicRing(8);
  const domeProfile = {
    points: [[1, 0], [1, 1], [0, 1]],
    weights: [1, SQRT1_2, 1],
    knots: [0, 0, 0, 1, 1, 1]
  };
  const dome = revolve(domeRing, domeProfile.points, domeProfile.weights, domeProfile.knots);
  const roundtop = sampleCad(dome, { resolution: [24, 12], collapsed: ['vmax'] });
  writeObj(path.join(outputDirectory, 'roundtop.obj'), roundtop);

  // Cone: straight meridian (collinear control points), apex at v = vmax.
  const coneRing = periodicRing(8);
  const coneProfile = {
    points: [[1, 0], [0.5, 0.5], [0, 1]],
    weights: [1, SQRT1_2, 1],
    knots: [0, 0, 0, 1, 1, 1]
  };
  const cone = revolve(coneRing, coneProfile.points, coneProfile.weights, coneProfile.knots);
  const coneMesh = sampleCad(cone, { resolution: [24, 12], collapsed: ['vmax'] });
  writeObj(path.join(outputDirectory, 'cone.obj'), coneMesh);

  console.log('CAD_POLES_EXAMPLE_OK roundtop_vertices=' + roundtop.positions.length / 3 +
    ' roundtop_triangles=' + roundtop.cells.length / 3 +
    ' cone_vertices=' + coneMesh.positions.length / 3 +
    ' cone_triangles=' + coneMesh.cells.length / 3);
}

main();
