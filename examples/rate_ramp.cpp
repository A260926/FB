// Rate ramp example: generates a stereo test signal whose right channel is
// the inverted left channel, runs it through RateTransposer in rate ramp
// mode (0.75 -> 1.5 over 60000 output frames, continuing at 1.5), and writes
// the per-output-frame source coordinate, the next rate and the output
// samples to a CSV file (default .build/rate-ramp.csv).
//
// The example mirrors the documented ramp clock (frame k uses source
// coordinate x_k and increment r_k = r0 + (rt - r0) * k / N, then
// x_{k+1} = x_k + r_k) and cross-checks it against the library's
// getCurrentRate() after every input chunk.

#include "RateTransposer.h"

#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <vector>

using namespace soundtouch;

#define EX_PI 3.14159265358979323846

int main(int argc, char **argv)
{
    const char *path = (argc > 1) ? argv[1] : ".build/rate-ramp.csv";

    const unsigned inFrames = 96000;        // 2 s at 48 kHz
    const unsigned rampN = 60000;           // ramp length in output frames
    const double r0 = 0.75, rt = 1.5;

    // stereo source: left = signal, right = -left (inverted channels)
    std::vector<float> input((size_t)inFrames * 2);
    for (unsigned i = 0; i < inFrames; i++)
    {
        double t = (double)i;
        double env = 0.5 + 0.5 * std::sin(2.0 * EX_PI * t / inFrames);
        double l = env * (0.30 * std::sin(2.0 * EX_PI * 0.004 * t)
                        + 0.15 * std::sin(2.0 * EX_PI * 0.011 * t + 0.7)
                        + 0.08 * std::sin(2.0 * EX_PI * 0.023 * t + 1.9));
        input[2 * i]     = (float)l;
        input[2 * i + 1] = (float)(-l);
    }

    TransposerBase::setAlgorithm(TransposerBase::CUBIC);
    RateTransposer transposer;
    transposer.setChannels(2);
    transposer.enableAAFilter(TRUE);
    transposer.enableRateRamp(TRUE);
    transposer.setRate((float)r0);
    transposer.setRateRamp(rt, rampN);

    FILE *csv = std::fopen(path, "wt");
    if (!csv)
    {
        std::fprintf(stderr, "cannot open %s\n", path);
        return 1;
    }
    std::fprintf(csv, "frame,src_coord,next_rate,left,right\n");

    // mirror of the documented trajectory, advanced once per drained frame
    double x = 0.0;
    unsigned long long done = 0, frameNo = 0;
    std::vector<float> buf;

    unsigned pos = 0;
    while (pos < inFrames)
    {
        unsigned n = (inFrames - pos > 256) ? 256 : inFrames - pos;
        transposer.putSamples(input.data() + (size_t)pos * 2, n);
        pos += n;

        // drain everything generated by this chunk
        for (;;)
        {
            unsigned avail = transposer.numSamples();
            if (avail == 0) break;
            buf.resize((size_t)avail * 2);
            unsigned got = transposer.receiveSamples(buf.data(), avail);
            if (got == 0) break;
            for (unsigned k = 0; k < got; k++)
            {
                double rate = (done < rampN) ? r0 + (rt - r0) * (double)done / (double)rampN : rt;
                std::fprintf(csv, "%llu,%.10f,%.10f,%.9g,%.9g\n",
                             frameNo, x, rate, buf[2 * k], buf[2 * k + 1]);
                x += rate;
                done++;
                frameNo++;
            }
        }

        // the library's idea of the next increment must match the mirror
        double expect = (done < rampN) ? r0 + (rt - r0) * (double)done / (double)rampN : rt;
        if (std::fabs(transposer.getCurrentRate() - expect) > 1e-12)
        {
            std::fprintf(stderr, "rate mismatch after %llu frames\n", done);
            std::fclose(csv);
            return 1;
        }
    }
    std::fclose(csv);
    std::printf("RATE_RAMP_EXAMPLE_OK frames=%llu final_coord=%.3f csv=%s\n",
                frameNo, x, path);
    return 0;
}
