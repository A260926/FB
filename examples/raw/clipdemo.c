/*
 * User clipping plane demo.
 *
 * Renders a hollow cylinder (a short pipe) cut open by two oblique planes and
 * writes the result as a binary PPM file (P6).  No caps are generated at the
 * cut, so the openings expose the inner wall - exactly what makes clipping
 * visible in an offline model preview.
 *
 * Pure C99 and TinyGL only.
 *
 *   make raw_examples
 *   ./clipdemo clipdemo.ppm
 */

#include <math.h>
#include <stdio.h>
#include <stdlib.h>

#include <TGL/gl.h>
#include "zbuffer.h"

#define WIDTH 480
#define HEIGHT 360
#define SEGMENTS 40

static void write_ppm(const char *name, ZBuffer *zb)
{
    FILE *f = fopen(name, "wb");
    int x, y;

    if (!f) {
        fprintf(stderr, "cannot open %s\n", name);
        exit(1);
    }
    fprintf(f, "P6\n%d %d\n255\n", zb->xsize, zb->ysize);
    for (y = 0; y < zb->ysize; y++)
        for (x = 0; x < zb->xsize; x++) {
            PIXEL p = zb->pbuf[y * zb->xsize + x];
            unsigned char rgb[3];
            rgb[0] = (unsigned char) GET_RED(p);
            rgb[1] = (unsigned char) GET_GREEN(p);
            rgb[2] = (unsigned char) GET_BLUE(p);
            fwrite(rgb, 1, 3, f);
        }
    fclose(f);
}

static void vertex_cyl(GLfloat r, GLfloat a, GLfloat z)
{
    glVertex3f(r * cosf(a), r * sinf(a), z);
}

/* Hollow cylinder around the Z axis, height [-h/2, h/2]. */
static void draw_pipe(GLfloat r_out, GLfloat r_in, GLfloat h)
{
    const GLfloat zt = h * 0.5f, zb = -h * 0.5f;
    GLint i;

    /* Outer wall: alternate the wall colour every few segments so the
     * silhouette reads as a tube even without lighting. */
    glBegin(GL_QUAD_STRIP);
    for (i = 0; i <= SEGMENTS; i++) {
        GLfloat a = (GLfloat) i * 2.0f * (GLfloat) M_PI / SEGMENTS;
        if ((i / 5) & 1)
            glColor3f(0.22f, 0.42f, 0.75f);
        else
            glColor3f(0.34f, 0.62f, 0.95f);
        glNormal3f(cosf(a), sinf(a), 0);
        vertex_cyl(r_out, a, zb);
        vertex_cyl(r_out, a, zt);
    }
    glEnd();

    /* inner wall (normals face inwards) */
    glBegin(GL_QUAD_STRIP);
    for (i = 0; i <= SEGMENTS; i++) {
        GLfloat a = (GLfloat) i * 2.0f * (GLfloat) M_PI / SEGMENTS;
        if ((i / 5) & 1)
            glColor3f(0.75f, 0.34f, 0.12f);
        else
            glColor3f(0.98f, 0.55f, 0.22f);
        glNormal3f(-cosf(a), -sinf(a), 0);
        vertex_cyl(r_in, a, zt);
        vertex_cyl(r_in, a, zb);
    }
    glEnd();

    /* top and bottom rims */
    glColor3f(0.95f, 0.85f, 0.30f);
    glBegin(GL_QUAD_STRIP);
    for (i = 0; i <= SEGMENTS; i++) {
        GLfloat a = (GLfloat) i * 2.0f * (GLfloat) M_PI / SEGMENTS;
        glNormal3f(0, 0, 1);
        vertex_cyl(r_out, a, zt);
        vertex_cyl(r_in, a, zt);
    }
    glEnd();
    glBegin(GL_QUAD_STRIP);
    for (i = 0; i <= SEGMENTS; i++) {
        GLfloat a = (GLfloat) i * 2.0f * (GLfloat) M_PI / SEGMENTS;
        glNormal3f(0, 0, -1);
        vertex_cyl(r_in, a, zb);
        vertex_cyl(r_out, a, zb);
    }
    glEnd();
}

int main(int argc, char **argv)
{
    const char *out = argc > 1 ? argv[1] : "clipdemo.ppm";
    ZBuffer *zb;
    GLdouble plane[4];

    zb = ZB_open(WIDTH, HEIGHT, ZB_MODE_RGBA, NULL);
    if (!zb)
        return 1;
    glInit(zb);

    glViewport(0, 0, WIDTH, HEIGHT);
    glClearColor(0.06f, 0.07f, 0.10f, 1.0f);
    glEnable(GL_DEPTH_TEST);
    glDepthMask(GL_TRUE);

    glMatrixMode(GL_PROJECTION);
    glLoadIdentity();
    glFrustum(-1.0, 1.0, -HEIGHT / (double) WIDTH, HEIGHT / (double) WIDTH,
              1.0, 80.0);

    glMatrixMode(GL_MODELVIEW);
    glLoadIdentity();
    glTranslatef(0.0f, 0.0f, -6.2f);
    glRotatef(38.0f, 1.0f, 0.0f, 0.0f);
    glRotatef(-32.0f, 0.0f, 1.0f, 0.0f);

    /*
     * Two cutting half spaces in object coordinates, ax+by+cz+d >= 0:
     *   plane 0 cuts the near side back along x
     *   plane 1 slices the upper-right wedge off with a diagonal plane
     * The two cuts intersect, so clipping a piece generated by the first
     * plane against the second one is exercised as well.
     */
    plane[0] = -0.9;
    plane[1] = 0.25;
    plane[2] = 0.0;
    plane[3] = 1.05;
    glClipPlane(GL_CLIP_PLANE0, plane);

    plane[0] = 0.45;
    plane[1] = 0.30;
    plane[2] = 0.84;
    plane[3] = 0.45;
    glClipPlane(GL_CLIP_PLANE1, plane);

    glEnable(GL_CLIP_PLANE0);
    glEnable(GL_CLIP_PLANE1);

    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);
    draw_pipe(2.2f, 1.45f, 3.4f);

    write_ppm(out, zb);

    glDisable(GL_CLIP_PLANE0);
    glDisable(GL_CLIP_PLANE1);
    glClose();
    ZB_close(zb);
    fprintf(stderr, "wrote %s\n", out);
    return 0;
}
