static void test_user_bits_mid_frame(void) {
	SMPTETimecode t = make_time("+0000", 0, 0, 0, 0, 0, 0, 0);
	const unsigned long first = 0x12345678UL;
	const unsigned long second = 0x9ABCDEF0UL;
	size_t spf = legacy_frame_length(48000, 25, LTC_TV_625_50, &t, -3.0, 40.0);
	LTCStreamEncoder *e;
	LTCStreamEncoder *ref_stream;
	ltcsnd_sample_t *buf;
	ltcsnd_sample_t *ref;
	int half;

	/* before any sample: applies to the current frame */
	e = ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
	CHECK_CHECK(e != NULL);
	buf = (ltcsnd_sample_t *) malloc(spf * 4);
	CHECK_CHECK(buf != NULL);
	if (e && buf) {
		BmcBits bits;
		CHECK_CHECK(ltc_stream_encoder_set_user_bits(e, first) == 0);
		ltc_stream_encoder_read(e, buf, spf);
		bmc_parse(buf, spf, 1, &bits);
		CHECK_CHECK(bits.count == LTC_FRAME_BIT_COUNT);
		CHECK_CHECK(bmc_user_bits(&bits) == first);
		free(buf);
		buf = NULL;
	}
	ltc_stream_encoder_free(e);

	/* mid-frame change: the first frame keeps `first`, the next uses
	 * `second`. Compare against a legacy encoder that receives the
	 * same call between the two frames. */
	{
		LTCEncoder *legacy = ltc_encoder_create(48000, 25, LTC_TV_625_50, 0);
		size_t total_ref = 0;
		ref = (ltcsnd_sample_t *) malloc(spf * 4);
		CHECK_CHECK(legacy != NULL);
		CHECK_CHECK(ref != NULL);
		if (!legacy || !ref) {
			ltc_encoder_free(legacy);
			free(ref);
			free(buf);
			return;
		}
		ltc_encoder_set_volume(legacy, -3.0);
		ltc_encoder_set_filter(legacy, 40.0);
		ltc_encoder_set_timecode(legacy, &t);
		legacy_set_user_bits_parity(legacy, first, LTC_TV_625_50, 0);
		ltc_encoder_encode_frame(legacy);
		total_ref += (size_t) ltc_encoder_copy_buffer(legacy, ref + total_ref);
		ltc_encoder_inc_timecode(legacy);
		legacy_set_user_bits_parity(legacy, second, LTC_TV_625_50, 0);
		ltc_encoder_encode_frame(legacy);
		total_ref += (size_t) ltc_encoder_copy_buffer(legacy, ref + total_ref);
		ltc_encoder_free(legacy);

		buf = (ltcsnd_sample_t *) malloc(spf * 4);
		CHECK_CHECK(buf != NULL);
		e = ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
		CHECK_CHECK(e != NULL);
		if (e && buf) {
			CHECK_CHECK(ltc_stream_encoder_set_user_bits(e, first) == 0);
			/* read past the middle of the first frame */
			half = (int) (spf / 2) + 7;
			CHECK_CHECK(ltc_stream_encoder_read(e, buf, half) == 0);
			CHECK_CHECK(ltc_stream_encoder_set_user_bits(e, second) == 0);
			CHECK_CHECK(ltc_stream_encoder_read(e, buf + half, spf - half) == 0);
			/* first frame is complete, now the second frame */
			CHECK_CHECK(ltc_stream_encoder_read(e, buf + spf, spf) == 0);
			CHECK_CHECK(memcmp(buf, ref, 2 * spf) == 0);
			ltc_stream_encoder_free(e);
		}
		free(ref);
		free(buf);
		buf = NULL;
	}

	/* a second change before the next frame starts is not lost */
	e = ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
	ref_stream = ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
	CHECK_CHECK(e != NULL);
	CHECK_CHECK(ref_stream != NULL);
	if (e && ref_stream) {
		ltcsnd_sample_t *a = (ltcsnd_sample_t *) malloc(spf * 2);
		ltcsnd_sample_t *b = (ltcsnd_sample_t *) malloc(spf * 2);
		CHECK_CHECK(a != NULL);
		CHECK_CHECK(b != NULL);
		if (a && b) {
			/* both streams start with the same first frame; only `e`
			 * changes the second frame user bits twice mid-frame */
			CHECK_CHECK(ltc_stream_encoder_read(e, a, 100) == 0);
			CHECK_CHECK(ltc_stream_encoder_read(ref_stream, b, 100) == 0);
			CHECK_CHECK(ltc_stream_encoder_set_user_bits(e, second) == 0);
			CHECK_CHECK(ltc_stream_encoder_set_user_bits(e, first) == 0);
			CHECK_CHECK(ltc_stream_encoder_read(e, a + 100, spf * 2 - 100) == 0);
			CHECK_CHECK(ltc_stream_encoder_read(ref_stream, b + 100, spf * 2 - 100) == 0);
			/* `e` changed the second frame to `first`; ref_stream still
			 * has the default user bits. They differ in frame 2. */
			CHECK_CHECK(memcmp(a, b, spf) == 0);
			CHECK_CHECK(memcmp(a + spf, b + spf, spf) != 0);
		}
		free(a);
		free(b);
	}
	ltc_stream_encoder_free(e);
	ltc_stream_encoder_free(ref_stream);

	/* LTC_USE_DATE refuses user-bit updates */
	{
		SMPTETimecode d = make_time("+0100", 24, 2, 28, 1, 2, 3, 4);
		e = ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, LTC_USE_DATE, &d, 1, -3.0, 40.0);
		CHECK_CHECK(e != NULL);
		if (e) {
			CHECK_CHECK(ltc_stream_encoder_set_user_bits(e, first) == -1);
			/* date is untouched by the failed call */
			{
				SMPTETimecode now;
				ltc_stream_encoder_get_timecode(e, &now);
				CHECK_CHECK(now.years == 24 && now.months == 2 && now.days == 28);
			}
			ltc_stream_encoder_free(e);
		}
	}
}

static void test_user_bits_parity(void) {
	/* The parity/correction bit lives at a standard-dependent place:
	 * bit 59 (byte 7) for 25 fps, bit 27 (byte 3) otherwise. */
	static const struct {
		enum LTC_TV_STANDARD standard;
		int parity_byte;
		int parity_mask;
	} cases[] = {
		{ LTC_TV_625_50, 7, 0x08 }, /* bit 59 */
		{ LTC_TV_525_60, 3, 0x08 }, /* bit 27 */
		{ LTC_TV_FILM_24, 3, 0x08 }
	};
	size_t ci;
	for (ci = 0; ci < ARRAY_LEN(cases); ci++) {
		SMPTETimecode t = make_time("+0000", 0, 0, 0, 4, 5, 6, 7);
		LTCStreamEncoder *e = ltc_stream_encoder_create(
				48000, 25, cases[ci].standard, 0, &t, 1, -3.0, 0.0);
		ltcsnd_sample_t buf[1920];
		BmcBits bits;
		CHECK_CHECK(e != NULL);
		if (!e) {
			continue;
		}
		CHECK_CHECK(ltc_stream_encoder_set_user_bits(e, 0xF0F0F0F0UL) == 0);
		CHECK_CHECK(ltc_stream_encoder_read(e, buf, 1920) == 0);
		bmc_parse(buf, 1920, 1, &bits);
		CHECK_CHECK(bits.count == LTC_FRAME_BIT_COUNT);
		CHECK_CHECK(bmc_parity_even(&bits));
		/* the user bits that were set are visible in the high nibbles */
		CHECK_CHECK(bmc_user_bits(&bits) == 0xF0F0F0F0UL);
		/* Pin the parity bit to the position the TV standard mandates:
		 * with all other 79 bits fixed, the parity bit makes the total
		 * number of ones even. A parity bit placed at the other
		 * standard's position would not satisfy this for an arbitrary
		 * user-bit payload. */
		{
			const int pb = cases[ci].parity_byte;
			int bb, k, ones = 0;
			for (bb = 0; bb < 10; bb++) {
				for (k = 0; k < 8; k++) {
					if (bb == pb && k == 3) {
						continue; /* the parity bit itself */
					}
					ones += (bits.bytes[bb] >> k) & 1;
				}
			}
			CHECK_CHECK(((bits.bytes[pb] >> 3) & 1) == (ones & 1));
		}
		ltc_stream_encoder_free(e);
	}

	/* LTC_NO_PARITY: a user-bit update must not touch the parity bit */
	{
		SMPTETimecode t = make_time("+0000", 0, 0, 0, 4, 5, 6, 7);
		LTCStreamEncoder *a = ltc_stream_encoder_create(
				48000, 25, LTC_TV_625_50, LTC_NO_PARITY, &t, 1, -3.0, 0.0);
		LTCStreamEncoder *b = ltc_stream_encoder_create(
				48000, 25, LTC_TV_625_50, LTC_NO_PARITY, &t, 1, -3.0, 0.0);
		ltcsnd_sample_t ba[1920], bb[1920];
		BmcBits x, y;
		CHECK_CHECK(a != NULL);
		CHECK_CHECK(b != NULL);
		if (a && b) {
			CHECK_CHECK(ltc_stream_encoder_set_user_bits(a, 0xF0F0F0F0UL) == 0);
			CHECK_CHECK(ltc_stream_encoder_read(a, ba, 1920) == 0);
			CHECK_CHECK(ltc_stream_encoder_read(b, bb, 1920) == 0);
			bmc_parse(ba, 1920, 1, &x);
			bmc_parse(bb, 1920, 1, &y);
			/* the parity bit (bit 59, byte 7 mask 0x08) is unchanged */
			CHECK_CHECK((x.bytes[7] & 0x08) == (y.bytes[7] & 0x08));
		}
		ltc_stream_encoder_free(a);
		ltc_stream_encoder_free(b);
	}
}

static void test_forward_bmc_edges(void) {
	/* Independently verify that the produced waveform is valid BMC for
	 * the requested timecode: decode the PCM and compare against the
	 * LTCFrame that ltc_time_to_frame builds for the same timecode. */
	SMPTETimecode t = make_time("+0000", 0, 0, 0, 12, 34, 56, 7);
	LTCFrame expected;
	ltc_frame_reset(&expected);
	ltc_time_to_frame(&expected, &t, LTC_TV_625_50, 0);

	{
		LTCStreamEncoder *e = ltc_stream_encoder_create(
				48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 0.0);
		ltcsnd_sample_t buf[1920];
		BmcBits bits;
		int i;
		CHECK_CHECK(e != NULL);
		if (!e) {
			return;
		}
		CHECK_CHECK(ltc_stream_encoder_read(e, buf, 1920) == 0);
		bmc_parse(buf, 1920, 1, &bits);
		CHECK_CHECK(bits.count == LTC_FRAME_BIT_COUNT);
		for (i = 0; i < 10; i++) {
			CHECK_CHECK(bits.bytes[i] == ((const unsigned char *) &expected)[i]);
		}
		ltc_stream_encoder_free(e);
	}

	/* reverse: decode backwards and compare to the reversed frame */
	{
		LTCStreamEncoder *e = ltc_stream_encoder_create(
				48000, 25, LTC_TV_625_50, 0, &t, -1, -3.0, 0.0);
		ltcsnd_sample_t buf[1920];
		BmcBits bits;
		int i;
		CHECK_CHECK(e != NULL);
		if (!e) {
			return;
		}
		CHECK_CHECK(ltc_stream_encoder_read(e, buf, 1920) == 0);
		bmc_parse(buf, 1920, -1, &bits);
		CHECK_CHECK(bits.count == LTC_FRAME_BIT_COUNT);
		for (i = 0; i < 10; i++) {
			CHECK_CHECK(bits.bytes[i] == ((const unsigned char *) &expected)[i]);
		}
		ltc_stream_encoder_free(e);
	}
}

static void test_chunk_invariance_edges(void) {
	/* every possible split point up to one frame length must yield the
	 * same stream. This covers splits on bit edges, half-bit edges and
	 * in the middle of a filtered edge. */
	SMPTETimecode t = make_time("+0000", 0, 0, 0, 1, 2, 3, 4);
	size_t spf = legacy_frame_length(48000, 25, LTC_TV_625_50, &t, -3.0, 40.0);
	LTCStreamEncoder *whole;
	ltcsnd_sample_t *ref = (ltcsnd_sample_t *) malloc(spf * 2);
	ltcsnd_sample_t *got = (ltcsnd_sample_t *) malloc(spf * 2);
	size_t split;

	CHECK_CHECK(ref != NULL);
	CHECK_CHECK(got != NULL);
	if (!ref || !got) {
		free(ref);
		free(got);
		return;
	}

	whole = ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
	CHECK_CHECK(whole != NULL);
	if (!whole) {
		free(ref);
		free(got);
		return;
	}
	CHECK_CHECK(ltc_stream_encoder_read(whole, ref, spf * 2) == 0);
	ltc_stream_encoder_free(whole);

	for (split = 1; split < spf; split += (split < 64 ? 1 : 37)) {
		LTCStreamEncoder *e = ltc_stream_encoder_create(
				48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
		CHECK_CHECK(e != NULL);
		if (!e) {
			continue;
		}
		CHECK_CHECK(ltc_stream_encoder_read(e, got, split) == 0);
		CHECK_CHECK(ltc_stream_encoder_read(e, got + split, spf - split) == 0);
		CHECK_CHECK(ltc_stream_encoder_read(e, got + spf, spf) == 0);
		CHECK_CHECK(memcmp(ref, got, spf * 2) == 0);
		ltc_stream_encoder_free(e);
	}

	free(ref);
	free(got);
}

static void test_read_does_not_touch_heap(void) {
#if HEAP_WRAPPING
	SMPTETimecode t = make_time("+0000", 0, 0, 0, 0, 0, 0, 0);
	LTCStreamEncoder *e = ltc_stream_encoder_create(
			48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
	ltcsnd_sample_t stack_buf[4096];
	unsigned long allocs_before, frees_before;
	int i;
	CHECK_CHECK(e != NULL);
	if (!e) {
		return;
	}

	heap_allocs = 0;
	heap_frees = 0;
	heap_guard = 1;
	for (i = 0; i < 200; i++) {
		CHECK_CHECK(ltc_stream_encoder_read(e, stack_buf, sizeof(stack_buf)) == 0);
	}
	heap_guard = 0;
	allocs_before = heap_allocs;
	frees_before = heap_frees;
	CHECK_CHECK(allocs_before == 0);
	CHECK_CHECK(frees_before == 0);

	/* sanity: the guard must be able to observe an allocation */
	heap_guard = 1;
	{
		void *p = malloc(16);
		free(p);
	}
	heap_guard = 0;
	CHECK_CHECK(heap_allocs > 0);

	ltc_stream_encoder_free(e);
#else
	/* Without a heap interposer the read path is still exercised at
	 * length; the fixed-size state is audited by design. */
	SMPTETimecode t = make_time("+0000", 0, 0, 0, 0, 0, 0, 0);
	LTCStreamEncoder *e = ltc_stream_encoder_create(
			48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
	ltcsnd_sample_t stack_buf[4096];
	int i;
	CHECK_CHECK(e != NULL);
	if (!e) {
		return;
	}
	for (i = 0; i < 200; i++) {
		CHECK_CHECK(ltc_stream_encoder_read(e, stack_buf, sizeof(stack_buf)) == 0);
	}
	ltc_stream_encoder_free(e);
#endif
}

