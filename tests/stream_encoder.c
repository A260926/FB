#if HEAP_WRAPPING
/*
 * The tests are linked with the static libltc.a. On Darwin the malloc
 * zone functions below take over the libc entry points for the whole
 * binary, so every allocation made by the library is counted while
 * heap_guard is enabled. The counters only look at the sample source
 * that lives in the archive, which is exactly what must stay
 * allocation-free.
 */
static int heap_guard = 0;
static unsigned long heap_allocs = 0;
static unsigned long heap_frees = 0;

void *malloc(size_t n) { if (heap_guard) ++heap_allocs; return malloc_zone_malloc(malloc_default_zone(), n); }
void *calloc(size_t n, size_t s) { if (heap_guard) ++heap_allocs; return malloc_zone_calloc(malloc_default_zone(), n, s); }
void *realloc(void *p, size_t n) { if (heap_guard) ++heap_allocs; return malloc_zone_realloc(malloc_default_zone(), p, n); }
void free(void *p) { if (heap_guard) ++heap_frees; malloc_zone_free(malloc_default_zone(), p); }
#endif

#define ARRAY_LEN(a) (sizeof(a) / sizeof((a)[0]))

/* ---------------- helpers ---------------- */

static SMPTETimecode make_time(const char *tz, int years, int months, int days,
                               int hours, int mins, int secs, int frame)
{
	SMPTETimecode t;
	memset(&t, 0, sizeof(t));
	if (tz) {
		strncpy(t.timezone, tz, sizeof(t.timezone) - 1);
	}
	t.years = (unsigned char) years;
	t.months = (unsigned char) months;
	t.days = (unsigned char) days;
	t.hours = (unsigned char) hours;
	t.mins = (unsigned char) mins;
	t.secs = (unsigned char) secs;
	t.frame = (unsigned char) frame;
	return t;
}

/*
 * Samples generated by the legacy encoder for exactly one frame. This
 * is the authoritative frame length (48000/25 -> 1920, not the buffer
 * size of 1921).
 */
static size_t legacy_frame_length(double sample_rate, double fps,
                                  enum LTC_TV_STANDARD standard,
                                  const SMPTETimecode *start,
                                  double volume, double rise_time)
{
	LTCEncoder *e = ltc_encoder_create(sample_rate, fps, standard, 0);
	SMPTETimecode t = *start;
	ltcsnd_sample_t *buf;
	int n;

	if (!e) {
		return 0;
	}
	ltc_encoder_set_volume(e, volume);
	ltc_encoder_set_filter(e, rise_time);
	ltc_encoder_set_timecode(e, &t);
	ltc_encoder_encode_frame(e);
	buf = (ltcsnd_sample_t *) malloc(ltc_encoder_get_buffersize(e) + 8);
	CHECK_CHECK(buf != NULL);
	n = buf ? ltc_encoder_copy_buffer(e, buf) : 0;
	free(buf);
	ltc_encoder_free(e);
	return (size_t) n;
}

/*
 * The legacy ltc_encoder_set_user_bits() writes the user fields but
 * does not refresh the parity/correction bit. The stream encoder does
 * that before the next frame starts, as required. To compare bytes the
 * reference frame is parity-corrected the same way, using the legacy
 * frame setter.
 */
static void legacy_set_user_bits_parity(LTCEncoder *e, unsigned long data,
                                        enum LTC_TV_STANDARD standard, int flags)
{
	LTCFrame f;
	ltc_encoder_set_user_bits(e, data);
	if (flags & LTC_NO_PARITY) {
		return;
	}
	ltc_encoder_get_frame(e, &f);
	ltc_frame_set_parity(&f, standard);
	ltc_encoder_set_frame(e, &f);
}

/* Pull `nframes` frames from the legacy encoder exactly the way an
 * application would (encode, copy, increment/decrement). */
static size_t encode_reference(double sample_rate, double fps,
                               enum LTC_TV_STANDARD standard, int flags,
                               const SMPTETimecode *start, int direction,
                               double volume, double rise_time,
                               int nframes, ltcsnd_sample_t **out,
                               int use_reversed_api)
{
	LTCEncoder *e = ltc_encoder_create(sample_rate, fps, standard, flags);
	SMPTETimecode t = *start;
	size_t cap = legacy_frame_length(sample_rate, fps, standard, start, volume, rise_time)
					* (size_t) (nframes + 2) + 64;
	size_t total = 0;
	ltcsnd_sample_t *buf;
	int i;

	CHECK_CHECK(e != NULL);
	if (!e) {
		*out = NULL;
		return 0;
	}
	ltc_encoder_set_volume(e, volume);
	ltc_encoder_set_filter(e, rise_time);
	ltc_encoder_set_timecode(e, &t);

	buf = (ltcsnd_sample_t *) malloc(cap);
	CHECK_CHECK(buf != NULL);
	if (!buf) {
		ltc_encoder_free(e);
		*out = NULL;
		return 0;
	}

	for (i = 0; i < nframes; i++) {
		if (use_reversed_api) {
			ltc_encoder_encode_reversed_frame(e);
		} else if (direction < 0) {
			ltc_encoder_encode_reversed_frame(e);
		} else {
			ltc_encoder_encode_frame(e);
		}
		total += (size_t) ltc_encoder_copy_buffer(e, buf + total);
		if (direction < 0) {
			ltc_encoder_dec_timecode(e);
		} else {
			ltc_encoder_inc_timecode(e);
		}
	}

	ltc_encoder_free(e);
	*out = buf;
	return total;
}

/* Pull a stream encoder in fixed or pseudo-random chunks. */
static void pull_chunked(LTCStreamEncoder *e, ltcsnd_sample_t *dst,
                         size_t total, size_t chunk, int randomize)
{
	size_t got = 0;
	unsigned long seed = 0x1234;
	while (got < total) {
		size_t n = chunk;
		if (randomize) {
			seed = seed * 1103515245UL + 12345UL;
			n = 1 + (seed >> 8) % 1000;
		}
		if (n > total - got) {
			n = total - got;
		}
		CHECK_CHECK(ltc_stream_encoder_read(e, dst + got, n) == 0);
		got += n;
	}
}

static void check_stream_matches_reference(
		const char *label, double sample_rate, double fps,
		enum LTC_TV_STANDARD standard, int flags,
		const SMPTETimecode *start, int direction,
		double volume, double rise_time, int nframes)
{
	static const size_t chunks[] = { 1, 2, 7, 63, 257, 1024 };
	ltcsnd_sample_t *ref = NULL;
	ltcsnd_sample_t *got = NULL;
	size_t total;
	size_t ci;

	total = encode_reference(sample_rate, fps, standard, flags, start, direction,
			volume, rise_time, nframes, &ref, 0);
	CHECK_CHECK(ref != NULL);
	CHECK_CHECK(total > 0);
	if (!ref) {
		return;
	}

	got = (ltcsnd_sample_t *) malloc(total);
	CHECK_CHECK(got != NULL);
	if (!got) {
		free(ref);
		return;
	}

	for (ci = 0; ci < ARRAY_LEN(chunks) + 1; ci++) {
		LTCStreamEncoder *e = ltc_stream_encoder_create(
				sample_rate, fps, standard, flags, start, direction,
				volume, rise_time);
		CHECK_CHECK(e != NULL);
		if (!e) {
			continue;
		}
		if (ci < ARRAY_LEN(chunks)) {
			pull_chunked(e, got, total, chunks[ci], 0);
		} else {
			pull_chunked(e, got, total, 0, 1);
		}
		CHECK_CHECK(memcmp(ref, got, total) == 0);
		if (memcmp(ref, got, total) != 0) {
			size_t i;
			for (i = 0; i < total; i++) {
				if (ref[i] != got[i]) {
					fprintf(stderr,
							"%s: first mismatch at %lu of %lu (ref=%u got=%u)\n",
							label, (unsigned long) i, (unsigned long) total,
							(unsigned int) ref[i], (unsigned int) got[i]);
					break;
				}
			}
		}
		ltc_stream_encoder_free(e);
	}

	free(ref);
	free(got);
}

/* ---------------- independent BMC helper ---------------- */

/*
 * Minimal, independent LTC reader used to check the stream encoder
 * without asking the library how it thinks the data should look.
 * It only trusts threshold crossings and the BMC rule, and works
 * forward or backward (byte 9 -> 0, MSB -> LSB).
 */
typedef struct BmcBits {
	unsigned char bytes[10];
	int count; /* valid bits, 0..80 */
} BmcBits;

static int sign_of(ltcsnd_sample_t s) {
	return s >= 128 ? 1 : 0;
}

/*
 * Reconstruct the 80 LTC bits from threshold crossings only.
 *
 * The stream starts exactly at bit 0, so the distance from sample 0 to
 * the first crossing is the length of the first BMC segment. A long
 * segment is a '0' bit; two consecutive short segments are a '1' bit
 * (short = half a bit-period). No knowledge of the encoder internals is
 * used beyond the BMC definition and the start-of-frame alignment.
 */
static void bmc_parse(const ltcsnd_sample_t *buf, size_t n, int direction,
                      BmcBits *out)
{
	size_t *edges;
	size_t *segs;
	int nedges = 0;
	int nsegs;
	size_t i;
	size_t minseg;

	memset(out, 0, sizeof(*out));
	if (n < 4) {
		return;
	}

	/* at most one crossing per sample; frames are small, so a fixed
	 * buffer is enough for a little more than one 80 bit frame */
	{
		static size_t edge_buf[512];
		static size_t seg_buf[512];
		edges = edge_buf;
		segs = seg_buf;
	}

	for (i = 1; i < n && nedges < 511; i++) {
		if (sign_of(buf[i]) != sign_of(buf[i - 1])) {
			edges[nedges++] = i;
		}
	}
	if (nedges < 1) {
		return;
	}

	/* segment lengths: from the frame start to the first crossing, then
	 * between crossings, and the final partial segment to the frame end */
	nsegs = 0;
	segs[nsegs++] = edges[0];
	for (i = 0; i + 1 < (size_t) nedges; i++) {
		segs[nsegs++] = edges[i + 1] - edges[i];
	}
	segs[nsegs++] = n - edges[nedges - 1];

	/* calibration: the shortest segment is half a bit-period. Frames
	 * always contain one bits (sync word), so a short segment exists. */
	minseg = segs[0];
	for (i = 1; i < (size_t) nsegs; i++) {
		if (segs[i] < minseg) {
			minseg = segs[i];
		}
	}
	if (minseg == 0) {
		return;
	}

	for (i = 0; i < (size_t) nsegs && out->count < LTC_FRAME_BIT_COUNT; ) {
		const int is_short = (segs[i] * 2 < minseg * 3);
		int bit_value;
		if (is_short) {
			/* a lone short segment at the very end is a truncated bit */
			if (i + 1 >= (size_t) nsegs) {
				break;
			}
			if (!(segs[i + 1] * 2 < minseg * 3)) {
				break;
			}
			bit_value = 1;
			i += 2;
		} else {
			bit_value = 0;
			i += 1;
		}
		{
			const int bit_index = out->count;
			const int byte_index = direction < 0 ? 9 - bit_index / 8 : bit_index / 8;
			const int step = bit_index % 8;
			const int mask = direction < 0 ? (128 >> step) : (1 << step);
			if (bit_value) {
				out->bytes[byte_index] |= (unsigned char) mask;
			}
			out->count++;
		}
	}
}

/* Check the parity rule on raw 80 bit data: even number of one bits. */
static int bmc_parity_even(const BmcBits *b) {
	int i, ones = 0;
	for (i = 0; i < 10; i++) {
		int k;
		for (k = 0; k < 8; k++) {
			ones += (b->bytes[i] >> k) & 1;
		}
	}
	return (ones % 2) == 0;
}

/* Compare the user-bits of a raw frame against a reference value.
 * user1 is the high nibble of byte 0, user2 the high nibble of byte 1,
 * and so on through user8 in the high nibble of byte 7. */
static unsigned long bmc_user_bits(const BmcBits *b) {
	unsigned long v = 0;
	int i;
	for (i = 7; i >= 0; i--) {
		v <<= 4;
		v += (b->bytes[i] >> 4) & 0xF;
	}
	return v;
}

/* ---------------- golden vectors ---------------- */

/*
 * FNV-1a over the complete PCM stream. These hashes were captured from
 * the original LTCEncoder before the stream encoder was added, so they
 * protect both the legacy output and the stream output against drift:
 * if either one changes the regression fires even when both encoders
 * change together.
 */
static unsigned long fnv1a(const unsigned char *p, size_t n) {
	unsigned long h = 2166136261UL;
	size_t i;
	for (i = 0; i < n; i++) {
		h ^= p[i];
		h *= 16777619UL;
	}
	return h & 0xffffffffUL;
}

typedef struct GoldenCase {
	const char *name;
	double sample_rate;
	double fps;
	enum LTC_TV_STANDARD standard;
	int flags;
	int direction;
	double volume;
	double rise_time;
	int nframes;
	unsigned long hash;
} GoldenCase;

static const GoldenCase golden_cases[] = {
	{ "fwd48k25",  48000, 25,               LTC_TV_625_50, 0, 1, -3.0, 40.0,  6, 0x6677ee9dUL },
	{ "rev48k25",  48000, 25,               LTC_TV_625_50, 0, -1, -3.0, 40.0,  6, 0xb1405c49UL },
	{ "df2997",    48000, 30000.0 / 1001.0, LTC_TV_525_60, 0, 1, -3.0, 40.0, 12, 0xa10cf757UL },
	{ "date44k",   44100, 24,               LTC_TV_FILM_24, LTC_USE_DATE, 1, -6.0, 40.0, 5, 0xc3808907UL },
	{ "sq192k",    192000, 24,              LTC_TV_FILM_24, 0, 1, -6.0, 0.0,   3, 0xb42aa4c5UL },
	{ "bgf30",     48000, 30,               LTC_TV_525_60, LTC_TC_CLOCK | LTC_BGF_DONT_TOUCH, 1, -3.0, 25.0, 3, 0xcfd82065UL }
};

static void test_golden_vectors(void) {
	size_t ci;
	for (ci = 0; ci < ARRAY_LEN(golden_cases); ci++) {
		const GoldenCase *g = &golden_cases[ci];
		SMPTETimecode t;
		ltcsnd_sample_t *ref = NULL;
		ltcsnd_sample_t *got;
		size_t total;
		LTCStreamEncoder *e;

		if (!strcmp(g->name, "df2997")) {
			t = make_time("+0000", 0, 0, 0, 0, 0, 59, 20);
		} else if (!strcmp(g->name, "date44k")) {
			t = make_time("+0100", 24, 2, 28, 23, 59, 59, 20);
		} else if (!strcmp(g->name, "bgf30") || !strcmp(g->name, "sq192k")) {
			t = make_time("+0000", 0, 0, 0, 0, 0, 0, 0);
		} else {
			t = make_time("+0100", 24, 2, 28, 1, 2, 3, 4);
		}

		total = encode_reference(g->sample_rate, g->fps, g->standard, g->flags,
				&t, g->direction, g->volume, g->rise_time, g->nframes,
				&ref, 0);
		CHECK_CHECK(ref != NULL);
		if (!ref) {
			continue;
		}
		CHECK_CHECK(fnv1a(ref, total) == g->hash);

		got = (ltcsnd_sample_t *) malloc(total);
		CHECK_CHECK(got != NULL);
		e = ltc_stream_encoder_create(g->sample_rate, g->fps, g->standard,
				g->flags, &t, g->direction, g->volume, g->rise_time);
		CHECK_CHECK(e != NULL);
		if (got && e) {
			pull_chunked(e, got, total, 257, 0);
			CHECK_CHECK(fnv1a(got, total) == g->hash);
			CHECK_CHECK(memcmp(ref, got, total) == 0);
		}
		ltc_stream_encoder_free(e);
		free(got);
		free(ref);
	}
}

