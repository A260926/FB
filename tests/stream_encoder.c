/**
   @brief regression tests for LTCStreamEncoder
   @file stream_encoder.c

   Covers the allocation-free streaming encoder:
   - byte-for-byte equality with the legacy LTCEncoder,
   - arbitrary read chunking (1 sample, odd sizes, filter mid-edge),
   - reverse playback, drop-frame minute boundaries and midnight date roll,
   - mid-frame user-bit updates and parity,
   - independent BMC edge / timecode checks,
   - no heap traffic inside ltc_stream_encoder_read().
*/

#include "ltc.h"
#include "test_support.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

