static void test_create_validation(void) {
	SMPTETimecode t = make_time("+0000", 24, 2, 28, 1, 2, 3, 4);
	const double good_fps[] = { 24.0, 25.0, 30.0, 30000.0 / 1001.0 };
	size_t i;

	for (i = 0; i < ARRAY_LEN(good_fps); i++) {
		LTCStreamEncoder *e = ltc_stream_encoder_create(
				48000, good_fps[i], LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
		CHECK_CHECK(e != NULL);
		ltc_stream_encoder_free(e);
	}

	/* unsupported fps and sample rates */
	CHECK_CHECK(ltc_stream_encoder_create(48000, 23.976, LTC_TV_525_60, 0, &t, 1, -3.0, 40.0) == NULL);
	CHECK_CHECK(ltc_stream_encoder_create(48000, 50.0, LTC_TV_525_60, 0, &t, 1, -3.0, 40.0) == NULL);
	CHECK_CHECK(ltc_stream_encoder_create(48000, 0.0, LTC_TV_525_60, 0, &t, 1, -3.0, 40.0) == NULL);
	CHECK_CHECK(ltc_stream_encoder_create(31999, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0) == NULL);
	CHECK_CHECK(ltc_stream_encoder_create(192001, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0) == NULL);

	/* direction must be exactly +1 or -1 */
	CHECK_CHECK(ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, &t, 0, -3.0, 40.0) == NULL);
	CHECK_CHECK(ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, &t, 2, -3.0, 40.0) == NULL);

	/* invalid volume and rise-time */
	CHECK_CHECK(ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, &t, 1, 1.0, 40.0) == NULL);
	CHECK_CHECK(ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, -1.0) == NULL);

	/* NULL start timecode */
	CHECK_CHECK(ltc_stream_encoder_create(48000, 25, LTC_TV_625_50, 0, NULL, 1, -3.0, 40.0) == NULL);

	/* boundary sample rates are accepted */
	{
		LTCStreamEncoder *a = ltc_stream_encoder_create(32000, 24, LTC_TV_FILM_24, 0, &t, 1, -3.0, 40.0);
		LTCStreamEncoder *b = ltc_stream_encoder_create(192000, 30, LTC_TV_525_60, 0, &t, 1, -3.0, 40.0);
		CHECK_CHECK(a != NULL);
		CHECK_CHECK(b != NULL);
		ltc_stream_encoder_free(a);
		ltc_stream_encoder_free(b);
	}

	/* read argument validation and zero-length semantics */
	{
		LTCStreamEncoder *e = ltc_stream_encoder_create(
				48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
		unsigned char byte = 0xAA;
		SMPTETimecode before, after;
		CHECK_CHECK(ltc_stream_encoder_read(e, NULL, 0) == 0);
		CHECK_CHECK(ltc_stream_encoder_read(e, NULL, 4) == -1);
		CHECK_CHECK(ltc_stream_encoder_read(NULL, &byte, 1) == -1);
		ltc_stream_encoder_get_timecode(e, &before);
		CHECK_CHECK(ltc_stream_encoder_read(e, &byte, 0) == 0);
		ltc_stream_encoder_get_timecode(e, &after);
		CHECK_CHECK(memcmp(&before, &after, sizeof(before)) == 0);
		ltc_stream_encoder_free(e);
	}

	/* free(NULL) is a no-op */
	ltc_stream_encoder_free(NULL);
}

static void test_forward_byte_identical(void) {
	SMPTETimecode t = make_time("+0100", 24, 2, 28, 1, 2, 3, 4);

	/* integer and fractional bit widths, every standard, both filters */
	check_stream_matches_reference("48k/25/625", 48000, 25, LTC_TV_625_50,
			0, &t, 1, -3.0, 40.0, 6);
	check_stream_matches_reference("44.1k/24/film", 44100, 24, LTC_TV_FILM_24,
			0, &t, 1, -6.0, 40.0, 5);
	check_stream_matches_reference("32k/30/525", 32000, 30, LTC_TV_525_60,
			0, &t, 1, -18.0, 40.0, 4);
	check_stream_matches_reference("96k/29.97/525", 96000, 30000.0 / 1001.0,
			LTC_TV_525_60, 0, &t, 1, -3.0, 40.0, 12);
	check_stream_matches_reference("192k/25/square", 192000, 25, LTC_TV_625_50,
			0, &t, 1, -3.0, 0.0, 3);
}

static void test_reverse_byte_identical(void) {
	SMPTETimecode t = make_time("+0100", 24, 2, 28, 1, 2, 3, 4);
	SMPTETimecode df = make_time("+0000", 0, 0, 0, 0, 0, 59, 20);

	check_stream_matches_reference("reverse/48k/25", 48000, 25, LTC_TV_625_50,
			0, &t, -1, -3.0, 40.0, 6);
	check_stream_matches_reference("reverse/48k/29.97", 48000, 30000.0 / 1001.0,
			LTC_TV_525_60, 0, &df, -1, -3.0, 40.0, 12);
	check_stream_matches_reference("reverse/192k/24", 192000, 24, LTC_TV_FILM_24,
			0, &t, -1, -3.0, 40.0, 4);
	check_stream_matches_reference("reverse/32k/30/square", 32000, 30, LTC_TV_525_60,
			0, &t, -1, -3.0, 0.0, 4);
}

static void test_reverse_is_not_forward_reversed(void) {
	/* Reverse playback must be its own bit-serial encoding, not the
	 * forward PCM copied backwards. Compare the first frame pulled in
	 * both directions: a sample-reversed forward frame would have the
	 * same multiset of transitions, but neither the byte layout nor the
	 * filtered shape matches. */
	SMPTETimecode t = make_time("+0000", 0, 0, 0, 1, 2, 3, 4);
	size_t spf = legacy_frame_length(48000, 25, LTC_TV_625_50, &t, -3.0, 40.0);
	LTCStreamEncoder *fwd = ltc_stream_encoder_create(
			48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
	LTCStreamEncoder *rev = ltc_stream_encoder_create(
			48000, 25, LTC_TV_625_50, 0, &t, -1, -3.0, 40.0);
	ltcsnd_sample_t *a = (ltcsnd_sample_t *) malloc(spf * 2);
	ltcsnd_sample_t *b = (ltcsnd_sample_t *) malloc(spf * 2);
	int reversed_copy = 1;
	size_t i;

	CHECK_CHECK(fwd != NULL);
	CHECK_CHECK(rev != NULL);
	CHECK_CHECK(a != NULL);
	CHECK_CHECK(b != NULL);
	if (!fwd || !rev || !a || !b) {
		free(a); free(b);
		ltc_stream_encoder_free(fwd);
		ltc_stream_encoder_free(rev);
		return;
	}

	CHECK_CHECK(ltc_stream_encoder_read(fwd, a, spf * 2) == 0);
	CHECK_CHECK(ltc_stream_encoder_read(rev, b, spf * 2) == 0);

	/* a pure whole-frame reverse copy would make frame k of one stream
	 * equal frame N-1-k of the other; here both start with the same
	 * timecode but encode its bits in opposite order, so that cannot
	 * hold and the two streams differ. */
	for (i = 0; i < spf * 2; i++) {
		if (b[i] != a[spf * 2 - 1 - i]) {
			reversed_copy = 0;
			break;
		}
	}
	CHECK_CHECK(reversed_copy == 0);

	/* and the two frames are not simply equal either */
	CHECK_CHECK(memcmp(a, b, spf) != 0);

	/* the reverse stream must decode to decreasing timecodes */
	{
		LTCDecoder *d = ltc_decoder_create((int) spf, 8);
		LTCFrameExt frame;
		int prev_valid = 0;
		int prev_frame = 0;
		int decoded = 0;
		CHECK_CHECK(d != NULL);
		if (d) {
			ltc_decoder_write(d, b, spf * 2, 0);
			while (ltc_decoder_read(d, &frame)) {
				SMPTETimecode dec;
				ltc_frame_to_time(&dec, &frame.ltc, 0);
				if (prev_valid) {
					CHECK_CHECK(dec.frame == prev_frame - 1 ||
					            (prev_frame == 0 && dec.frame >= 20));
				}
				prev_frame = dec.frame;
				prev_valid = 1;
				decoded++;
			}
			CHECK_CHECK(decoded >= 1);
			ltc_decoder_free(d);
		}
	}

	free(a);
	free(b);
	ltc_stream_encoder_free(fwd);
	ltc_stream_encoder_free(rev);
}

static void test_timecode_lookup_boundaries(void) {
	/* The legacy encoder's per-frame copy length is the independent
	 * ground truth for how many samples a frame occupies. */
	{
		SMPTETimecode t = make_time("+0000", 0, 0, 0, 0, 0, 59, 24);
		LTCEncoder *legacy = ltc_encoder_create(48000, 25, LTC_TV_625_50, 0);
		size_t spf;
		ltcsnd_sample_t *dummy;
		CHECK_CHECK(legacy != NULL);
		if (!legacy) {
			return;
		}
		dummy = (ltcsnd_sample_t *) malloc(ltc_encoder_get_buffersize(legacy));
		CHECK_CHECK(dummy != NULL);
		ltc_encoder_set_timecode(legacy, &t);
		ltc_encoder_encode_frame(legacy);
		spf = dummy ? (size_t) ltc_encoder_copy_buffer(legacy, dummy) : 0;
		free(dummy);
		ltc_encoder_free(legacy);
		CHECK_CHECK(spf == 1920);

		/* forward: report the frame owning the next sample */
		{
			LTCStreamEncoder *e = ltc_stream_encoder_create(
					48000, 25, LTC_TV_625_50, 0, &t, 1, -3.0, 40.0);
			ltcsnd_sample_t buf[256];
			SMPTETimecode now;
			size_t n = 0;

			CHECK_CHECK(e != NULL);
			if (!e) {
				return;
			}

			ltc_stream_encoder_get_timecode(e, &now);
			CHECK_CHECK(now.secs == 59 && now.frame == 24);

			while (n + 100 < spf) {
				ltc_stream_encoder_read(e, buf, 100);
				n += 100;
				ltc_stream_encoder_get_timecode(e, &now);
				CHECK_CHECK(now.secs == 59 && now.frame == 24);
			}
			/* consume the remaining samples of the frame one by one;
			 * until the very last sample the current frame is reported */
			while (n + 1 < spf) {
				ltc_stream_encoder_read(e, buf, 1);
				n++;
				ltc_stream_encoder_get_timecode(e, &now);
				CHECK_CHECK(now.secs == 59 && now.frame == 24);
			}
			/* the very last sample still belongs to the current frame */
			ltc_stream_encoder_read(e, buf, 1);
			ltc_stream_encoder_get_timecode(e, &now);
			CHECK_CHECK(now.mins == 1 && now.secs == 0 && now.frame == 0);
			ltc_stream_encoder_free(e);
		}
	}

	/* reverse: previous frame after the last sample of the current one */
	{
		SMPTETimecode t = make_time("+0000", 0, 0, 0, 0, 0, 1, 0);
		size_t spf = 1920;
		LTCStreamEncoder *e = ltc_stream_encoder_create(
				48000, 25, LTC_TV_625_50, 0, &t, -1, -3.0, 40.0);
		ltcsnd_sample_t *buf = (ltcsnd_sample_t *) malloc(spf);
		SMPTETimecode now;
		CHECK_CHECK(e != NULL);
		CHECK_CHECK(buf != NULL);
		if (e && buf) {
			ltc_stream_encoder_read(e, buf, spf);
			ltc_stream_encoder_get_timecode(e, &now);
			CHECK_CHECK(now.secs == 0 && now.frame == 24);
		}
		free(buf);
		ltc_stream_encoder_free(e);
	}
}

static void test_drop_frame_minute_boundary(void) {
	/* 29.97 DF: at 00:00:59:29 the next frame is 00:01:00:02 */
	SMPTETimecode t = make_time("+0000", 0, 0, 0, 0, 0, 59, 29);
	size_t spf = legacy_frame_length(48000, 30000.0 / 1001.0, LTC_TV_525_60, &t, -3.0, 40.0);
	LTCStreamEncoder *e = ltc_stream_encoder_create(
			48000, 30000.0 / 1001.0, LTC_TV_525_60, 0, &t, 1, -3.0, 40.0);
	LTCEncoder *legacy = ltc_encoder_create(
			48000, 30000.0 / 1001.0, LTC_TV_525_60, 0);
	ltcsnd_sample_t *buf = (ltcsnd_sample_t *) malloc(spf);
	ltcsnd_sample_t *ref = (ltcsnd_sample_t *) malloc(spf);
	SMPTETimecode now;
	CHECK_CHECK(e != NULL);
	CHECK_CHECK(legacy != NULL);
	CHECK_CHECK(buf != NULL);
	CHECK_CHECK(ref != NULL);
	if (e && legacy && buf && ref) {
		ltc_encoder_set_timecode(legacy, &t);
		ltc_encoder_encode_frame(legacy);
		CHECK_CHECK((size_t) ltc_encoder_copy_buffer(legacy, ref) == spf);

		/* The first frame is bit-identical to the legacy encoder even
		 * though the *next* timecode jumps over the dropped numbers. */
		ltc_stream_encoder_read(e, buf, spf);
		CHECK_CHECK(memcmp(buf, ref, spf) == 0);
		ltc_stream_encoder_get_timecode(e, &now);
		CHECK_CHECK(now.mins == 1 && now.secs == 0 && now.frame == 2);
		ltc_encoder_inc_timecode(legacy);
		ltc_encoder_get_timecode(legacy, &now);
		CHECK_CHECK(now.mins == 1 && now.secs == 0 && now.frame == 2);

		/* the following frame continues at :03 */
		ltc_stream_encoder_read(e, buf, spf);
		ltc_stream_encoder_get_timecode(e, &now);
		CHECK_CHECK(now.mins == 1 && now.secs == 0 && now.frame == 3);
	}
	free(buf);
	free(ref);
	ltc_encoder_free(legacy);
	ltc_stream_encoder_free(e);

	/* reverse at 00:01:00:02 must skip back over the dropped numbers
	 * to 00:00:59:29 */
	t = make_time("+0000", 0, 0, 0, 0, 1, 0, 2);
	e = ltc_stream_encoder_create(
			48000, 30000.0 / 1001.0, LTC_TV_525_60, 0, &t, -1, -3.0, 40.0);
	buf = (ltcsnd_sample_t *) malloc(spf);
	legacy = ltc_encoder_create(48000, 30000.0 / 1001.0, LTC_TV_525_60, 0);
	CHECK_CHECK(e != NULL);
	CHECK_CHECK(legacy != NULL);
	CHECK_CHECK(buf != NULL);
	if (e && legacy && buf) {
		ltc_stream_encoder_read(e, buf, spf);
		ltc_stream_encoder_get_timecode(e, &now);
		CHECK_CHECK(now.mins == 0 && now.secs == 59 && now.frame == 29);
		ltc_encoder_set_timecode(legacy, &t);
		ltc_encoder_dec_timecode(legacy);
		ltc_encoder_get_timecode(legacy, &now);
		CHECK_CHECK(now.mins == 0 && now.secs == 59 && now.frame == 29);
	}
	free(buf);
	ltc_encoder_free(legacy);
	ltc_stream_encoder_free(e);
}

