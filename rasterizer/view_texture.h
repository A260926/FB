#pragma once

#include "renderer.h"

#include "texture.h"
#include "math/matrix4.h"
#include "math/vector2.h"
#include "math/vector3.h"
#include "math/vector4.h"

#include <array>
#include <cstddef>
#include <string>
#include <vector>

/*
 * Texture source selection for an indexed triangle mesh without UVs.
 *
 * Every original triangle face is tested against two source cameras.  The
 * per-face visibility statistics are gathered with one full-mesh raster pass
 * per source camera (plus one full-grid resolve pass for the depth winners).
 * A face may use a source camera when all three of its original vertices are
 * inside that camera's clip volume, at least one target pixel center is
 * covered, and every covered pixel wins the depth test.
 *
 * The binary source labels are the exact global minimum of
 *
 *     sum_i U(i, label_i) + seamPenalty * #{ interior edges with label_i != label_j }
 *     U(i, c) = W*H - Covered(i, c)
 *
 * solved with an s-t minimum cut.  Faces without an allowed source are -1.
 */
namespace view_texture
{

/* Shared-position indexed triangle mesh, positions are in world space. */
struct Mesh
{
    std::vector<Vec3> positions;
    std::vector<unsigned int> indices;   /* three entries per face */
};

/* Clip matrix and linear Vec4 colour texture of one source camera. */
struct SourceCamera
{
    Mat4 world_to_clip = Mat4::identity();
    const Texture<Vec4>* texture = nullptr;
};

/* World to homogeneous clip matrix of the ordinary viewing camera. */
struct ObserverCamera
{
    Mat4 world_to_clip = Mat4::identity();
};

struct FaceVisibility
{
    int covered = 0;
    int won = 0;
    bool selectable = false;
    int shards = 0;   /* clipped fan shards generated by this face */
};

/*
 * Self-contained result of a selection.  It owns its statistics and labels;
 * selecting again never mutates a previously returned Selection.  The source
 * textures are not owned, the caller keeps them alive while drawing.
 */
struct Selection
{
    bool valid = false;
    std::string error;

    unsigned int width = 0;
    unsigned int height = 0;
    int seam_penalty = 0;

    std::vector<std::array<FaceVisibility, 2>> visibility;
    std::vector<int> labels;       /* -1, 0 or 1 per original face */
    long long energy = 0;
};

/*
 * Low level binary labelling problem, exposed so the exact solver can be
 * exercised independently of the rasterizer.
 *
 * covered[face][source] < 0 marks a forbidden source; otherwise it is the
 * number of covered samples in [0, width*height].  indices must contain three
 * shared position indices per face and vertex_count bounds them.
 */
struct LabelProblem
{
    unsigned int width = 0;
    unsigned int height = 0;
    int seam_penalty = 0;
    std::size_t vertex_count = 0;
    std::vector<unsigned int> indices;
    std::vector<std::array<int, 2>> covered;
};

struct LabelResult
{
    bool valid = false;
    std::string error;
    std::vector<int> labels;
    long long energy = 0;
};

/* Exact global minimum for the binary labelling problem (min s-t cut). */
LabelResult solve_labels(const LabelProblem& problem);

/*
 * Rasterize the whole mesh once per source camera and solve the labels.
 * Invalid topology, indices, degeneracies, non-finite values or mismatched
 * textures are rejected and leave valid == false.
 */
Selection select(const Mesh& mesh,
                 const std::array<SourceCamera, 2>& sources,
                 int seam_penalty);

/*
 * Bilinear tap of a linear Vec4 texture using uv*size-0.5, floor for the
 * lower texel and a clamp for every one of the four neighbouring texels.
 * Texture storage is y-up, matching the source camera convention.
 */
Vec4 sample_bilinear(const Texture<Vec4>& texture, const Vec2& uv);

/*
 * Draw the mesh with the ordinary Renderer triangle pipeline under the
 * observer camera.  Each face is submitted with its flat label held in a
 * uniform (the label is never interpolated as a fragment attribute); the
 * selected source matrix projects the perspective-correct world position per
 * fragment.  Faces labelled -1 use fallback_color.  The framebuffer is not
 * cleared.
 *
 * Returns false when the inputs are unusable (invalid selection, label count
 * mismatch, null/incompatible textures, non-finite observer matrix).
 */
bool draw(Renderer& renderer,
          const Mesh& mesh,
          const Selection& selection,
          const std::array<SourceCamera, 2>& sources,
          const ObserverCamera& observer,
          const Vec4& fallback_color);

} /* namespace view_texture */
