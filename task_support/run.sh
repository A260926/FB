#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."
mode=${1:-baseline}
if [[ $mode == target ]]; then test -s tests/checkpoint_task.cc; fi
mkdir -p .task-build
required_object=
if [[ $mode == target ]]; then
  test -s libde265/checkpoint.cc
  test -s libde265/checkpoint.h
fi
cmake -S . -B .task-build/de265 -DCMAKE_BUILD_TYPE=Release -DBUILD_SHARED_LIBS=OFF -DENABLE_SDL=OFF -DENABLE_SIMD=OFF -DENABLE_DECODER=OFF -DENABLE_ENCODER=OFF -DENABLE_SHERLOCK265=OFF -DENABLE_INTERNAL_DEVELOPMENT_TOOLS=OFF >.task-build/configure.log 2>&1 || { tail -30 .task-build/configure.log; exit 1; }
cmake --build .task-build/de265 --target de265 -j4 >.task-build/build.log 2>&1 || { tail -30 .task-build/build.log; exit 1; }
if [[ $mode == target ]]; then
  c++ -std=c++17 -DHAVE_CONFIG_H -I. -I.task-build/de265 -I.task-build/de265/libde265 -x c++ -c -include libde265/checkpoint.h /dev/null -o .task-build/required-header.o
  required_object=.task-build/de265/libde265/CMakeFiles/de265.dir/checkpoint.cc.o
  test -s "$required_object"
  ar t .task-build/de265/libde265/libde265.a | grep -qx checkpoint.cc.o
  required_object="$required_object .task-build/required-header.o"
fi
c++ -std=c++17 -DHAVE_CONFIG_H -DLIBDE265_STATIC_BUILD -I. -I.task-build/de265 -I.task-build/de265/libde265 task_support/baseline.cpp $required_object .task-build/de265/libde265/libde265.a -pthread -o .task-build/baseline
if [[ $mode == target ]]; then
  test -s examples/checkpoint_demo.cc
c++ -std=c++17 -DHAVE_CONFIG_H -DLIBDE265_STATIC_BUILD -I. -I.task-build/de265 -I.task-build/de265/libde265 examples/checkpoint_demo.cc $required_object .task-build/de265/libde265/libde265.a -pthread -o .task-build/checkpoint-demo
# Delete only files generated by this example on previous runs.
rm -f .task-build/checkpoint.bin .task-build/checkpoint.cursor .task-build/checkpoint.suffix.h265 .task-build/checkpoint.expected .task-build/checkpoint.actual
.task-build/checkpoint-demo save testdata/girlshy.h265 .task-build/checkpoint.bin .task-build/checkpoint.cursor .task-build/checkpoint.suffix.h265 .task-build/checkpoint.expected
for p in .task-build/checkpoint.bin .task-build/checkpoint.cursor .task-build/checkpoint.suffix.h265 .task-build/checkpoint.expected; do test -s "$p"; done
.task-build/checkpoint-demo resume .task-build/checkpoint.bin .task-build/checkpoint.cursor .task-build/checkpoint.suffix.h265 .task-build/checkpoint.actual
test -s .task-build/checkpoint.actual
.task-build/checkpoint-demo verify .task-build/checkpoint.expected .task-build/checkpoint.actual
c++ -std=c++17 -DHAVE_CONFIG_H -DLIBDE265_STATIC_BUILD -I. -I.task-build/de265 -I.task-build/de265/libde265 task_support/driver.c tests/checkpoint_task.cc $required_object .task-build/de265/libde265/libde265.a -pthread -o .task-build/target
  output_log=$(mktemp)
  trap 'rm -f "$output_log"' EXIT
  set +e
  .task-build/target >"$output_log" 2>&1
  status=$?
  set -e
  cat "$output_log"
  [[ $status == 0 ]] || exit "$status"
  for group in format reference process; do
    grep -Eq "^GROUP ${group} cases=[1-9][0-9]* checks=[1-9][0-9]* COMPLETE$" "$output_log"
  done
  grep -Eq '^TARGET_COMPLETE cases=[1-9][0-9]*$' "$output_log"
fi
.task-build/baseline
