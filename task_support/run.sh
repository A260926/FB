#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."
mode=${1:-baseline}
if [[ $mode == target ]]; then test -s checks/target.cpp; fi
bash checks/build.sh
if [[ $mode == target ]]; then
  test -s examples/queued_queries.cpp
bash checks/link.sh .task-build/example examples/queued_queries.cpp
.task-build/example
bash checks/link.sh .task-build/target checks/target.cpp task_support/driver.c
  output_log=$(mktemp)
  trap 'rm -f "$output_log"' EXIT
  set +e
  .task-build/target >"$output_log" 2>&1
  status=$?
  set -e
  cat "$output_log"
  [[ $status == 0 ]] || exit "$status"
  for group in prefix lifetime partition; do
    grep -Eq "^GROUP ${group} cases=[1-9][0-9]* checks=[1-9][0-9]* COMPLETE$" "$output_log"
  done
  grep -Eq '^TARGET_COMPLETE cases=[1-9][0-9]*$' "$output_log"
fi
if [[ $mode == baseline ]]; then bash checks/baseline.sh; fi
