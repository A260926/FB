import assert from 'node:assert/strict';
import { NullGraphicsDevice } from '../src/platform/graphics/null/null-graphics-device.js';
import { SEMANTIC_BLENDINDICES, SEMANTIC_BLENDWEIGHT, TYPE_UINT8 } from '../src/platform/graphics/constants.js';
import { Mat4 } from '../src/core/math/mat4.js';
import { Vec3 } from '../src/core/math/vec3.js';
import { GraphNode } from '../src/scene/graph-node.js';
import { Skin } from '../src/scene/skin.js';
import { SkinInstance } from '../src/scene/skin-instance.js';
import { Mesh } from '../src/scene/mesh.js';
import { MeshInstance } from '../src/scene/mesh-instance.js';
import { Scene } from '../src/scene/scene.js';
import { Renderer } from '../src/scene/renderer/renderer.js';
import { StandardMaterial } from '../src/scene/materials/standard-material.js';
import { AnimData } from '../src/framework/anim/evaluator/anim-data.js';
import { AnimTrack } from '../src/framework/anim/evaluator/anim-track.js';
import { AnimCurve } from '../src/framework/anim/evaluator/anim-curve.js';
import { AnimClip } from '../src/framework/anim/evaluator/anim-clip.js';
import { AnimEvaluator } from '../src/framework/anim/evaluator/anim-evaluator.js';
import { DefaultAnimBinder } from '../src/framework/anim/binder/default-anim-binder.js';
import { INTERPOLATION_LINEAR } from '../src/framework/anim/constants.js';
const device = new NullGraphicsDevice();
const root = new GraphNode('character'); root.setLocalPosition(10, 0, 0);
const bones = [];
for (let i = 0; i < 5; ++i) {
    const bone = new GraphNode(`bone${i}`);
    if (i) bone.setLocalPosition(0, 1, 0);
    (i ? bones[i - 1] : root).addChild(bone); bones.push(bone);
}
const skin = new Skin(device, bones.map((_, i) => new Mat4().setTranslate(0, -i, 0)), bones.map(b => b.name));
const si = new SkinInstance(skin); si.bones = bones;
const mesh = new Mesh(device);
mesh.setPositions([0,0,0, 1,0,0, 0,1,0]);
mesh.setVertexStream(SEMANTIC_BLENDINDICES, new Uint8Array([0,4,0,0, 0,4,0,0, 0,4,0,0]),4,3,TYPE_UINT8);
mesh.setVertexStream(SEMANTIC_BLENDWEIGHT, new Float32Array([.5,.5,0,0, .5,.5,0,0, .5,.5,0,0]),4);
mesh.setIndices([0,1,2]); mesh.skin = skin; mesh.update();
const material = new StandardMaterial();
const mi = new MeshInstance(mesh, material, root); mi.skinInstance = si;
const track = new AnimTrack('move',1,[new AnimData(1,[0,1])],[new AnimData(3,[0,0,0,2,0,0])],[new AnimCurve([{entityPath:['bone0'],component:'graph',propertyPath:['localPosition']}],0,0,INTERPOLATION_LINEAR)]);
const evaluator = new AnimEvaluator(new DefaultAnimBinder(root)); evaluator.addClip(new AnimClip(track,0,1,true,false));
evaluator.update(.25);
const scene = new Scene(device); scene.clusteredLightingEnabled = false;
const renderer = new Renderer(device, scene);
renderer.updateCpuSkinMatrices([mi]);
const bound = mi.aabb;
renderer.updateGpuSkinMatrices([mi]); renderer.setSkinning(device,mi);
assert.equal(device.scope.resolve('texture_poseMap').value, si.boneTexture);
assert.equal(si.bones.length,5);
assert.ok(Math.abs(si.matrixPalette[3] - .5) < 1e-6);
const p = new Vec3(); si.matrices[0].transformPoint(Vec3.ZERO,p); root.getWorldTransform().transformPoint(p,p);
assert.ok(Math.abs(p.x - 10.5) < 1e-6);
assert.ok(bound.containsPoint(p)); assert.ok(bound.containsPoint(new Vec3(11.5,0,0)));
console.log(`ANIM_SKIN x=${p.x.toFixed(6)} bones=${si.bones.length} palette=${si.matrixPalette.length}`);
console.log('PLAYCANVAS_SINGLE_SKIN_OK');
renderer.destroy(); mi.destroy(); material.destroy(); device.destroy();
