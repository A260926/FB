import assert from 'node:assert/strict';
import { Scene } from '../src/scenes/Scene.js';
import { Object3D } from '../src/scenes/Object3D.js';
import { Camera } from '../src/scenes/Camera.js';
import { Mesh } from '../src/scenes/Mesh.js';
import { SkinnedMesh } from '../src/scenes/SkinnedMesh.js';
import { Bone } from '../src/scenes/Bone.js';
import { Skeleton } from '../src/resources/Skeleton.js';
import { Geometry } from '../src/resources/geometries/Geometry.js';
import { BasicMaterial } from '../src/resources/materials/BasicMaterial.js';
import { AmbientLight } from '../src/scenes/lights/AmbientLight.js';
import { Matrix4 } from '../src/math/Matrix4.js';
const scene = new Scene(), camera = new Camera(), other = new Camera();
camera.setPerspective(Math.PI / 2, 1, 1, 100); other.setPerspective(Math.PI / 2, 1, 1, 100);
scene.add(camera); scene.add(other);
const geometry = new Geometry(); geometry.boundingSphere.center.set(0, 0, 0); geometry.boundingSphere.radius = 0.2;
geometry.addGroup(0, 3, 0); geometry.addGroup(3, 3, 1);
const opaque = new BasicMaterial(), transparent = new BasicMaterial(); transparent.transparent = true;
const a = new Mesh(geometry, opaque); a.position.set(-1, 0, -5); scene.add(a);
const grouped = new Mesh(geometry, [opaque, transparent]); grouped.position.set(1, 0, -5); grouped.renderLayer = 2; scene.add(grouped);
const hidden = new Object3D(); hidden.visible = false; hidden.add(new Mesh(geometry, opaque)); scene.add(hidden);
const outside = new Mesh(geometry, opaque); outside.position.set(1000, 0, -5); scene.add(outside);
const bone = new Bone(); bone.position.x = 0.4; scene.add(bone);
const skeleton = new Skeleton([bone], [new Matrix4()]); let updates = 0;
const update = skeleton.updateBones.bind(skeleton); skeleton.updateBones = function(data) { updates++; update(data); };
for (let i = 0; i < 2; i++) { const mesh = new SkinnedMesh(geometry, opaque); mesh.position.set(0, i * 0.2, -5); mesh.skeleton = skeleton; scene.add(mesh); }
const light = new AmbientLight(); scene.add(light);
scene.updateMatrix(); scene.updateRenderStates(camera);
const queue = scene.updateRenderQueue(camera);
const entries = q => q.layerList.flatMap(l => [...l.opaque, ...l.transparent]);
assert.equal(entries(queue).length, 5);
assert.equal(queue.getLayer(2).opaqueCount, 1); assert.equal(queue.getLayer(2).transparentCount, 1);
assert.equal(queue.skeletons.size, 1); assert.equal(updates, 1); assert.ok(Math.abs(skeleton.boneMatrices[12] - 0.4) < 1e-6);
assert.equal(scene.getRenderStates(camera).lighting.lightsArray[0], light);
assert.ok(!entries(queue).some(r => r.object === outside));
scene.updateRenderStates(other); const otherQueue = scene.updateRenderQueue(other, false, false);
assert.notEqual(queue, otherQueue); assert.equal(updates, 1); assert.equal(entries(otherQueue).length, 5);
scene.remove(grouped); scene.updateMatrix(); scene.updateRenderQueue(camera, true, true);
assert.equal(updates, 2); assert.equal(entries(queue).length, 3); assert.equal(queue.getLayer(2).opaqueCount, 0); assert.equal(queue.getLayer(2).transparentCount, 0);
scene.add(grouped); scene.updateMatrix(); scene.updateRenderQueue(camera, false, false);
assert.equal(entries(queue).length, 5);
console.log('T3D_SCENE_BASELINE_OK entries=5 groups=2 sharedSkeletonUpdates=2 cameras=2 detach=clean');
