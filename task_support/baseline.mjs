import assert from 'node:assert/strict';
import {Scene,Camera,Object3D,Mesh,BoxGeometry,BasicMaterial,Skeleton,Bone,Matrix4} from '../src/main.js';
const scene=new Scene(), root=new Object3D(), geometry=new BoxGeometry();
const opaque=new BasicMaterial(), transparent=new BasicMaterial(); transparent.transparent=true;
const a=new Mesh(geometry,[opaque,transparent]), b=new Mesh(geometry,opaque);
a.position.x=-1; b.position.x=1; a.renderLayer=2;
root.add(a);root.add(b);scene.add(root);
const bone=new Bone();bone.position.x=.25;scene.add(bone);
const skeleton=new Skeleton([bone],[new Matrix4()]);a.skeleton=skeleton;b.skeleton=skeleton;
let updates=0;const update=skeleton.updateBones.bind(skeleton);skeleton.updateBones=d=>{updates++;update(d);};
const camera=new Camera();camera.position.z=5;camera.setPerspective(Math.PI/3,1,.1,100);
const away=new Camera();away.position.set(100,0,5);away.setPerspective(Math.PI/3,1,.1,100);
scene.updateMatrix();camera.updateMatrix();away.updateMatrix();
const collect=c=>{scene.updateRenderStates(c);return scene.updateRenderQueue(c,false,false);};
const entries=q=>q.layerList.flatMap(l=>[...l.opaque,...l.transparent]);
let queue=collect(camera);assert.equal(entries(queue).length,3);assert.equal(queue.getLayer(2).transparent.length,1);assert.equal(updates,1);
assert.equal(skeleton.boneMatrices[12],.25);assert.equal(a.geometry,b.geometry);
assert.equal(entries(collect(away)).length,0);assert.equal(updates,1);
assert.equal(entries(collect(camera)).length,3);assert.equal(updates,1);
root.visible=false;assert.equal(entries(collect(camera)).length,0);
root.visible=true;b.position.x=100;scene.updateMatrix();assert.equal(entries(collect(camera)).length,2);
console.log('SCENE_QUEUE_BASELINE entries=3 away=0 moved=2 skeleton_updates='+updates);
